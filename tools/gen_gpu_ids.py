#!/usr/bin/env python3
"""gen_gpu_ids.py - the GPU identification tables (Milestone 112).

    tools/gen_gpu_ids.py <linux-tree-or-dir> > include/gpu64_ids.h

Reads two MIT-licensed files from Linux - Intel's PCI ID list
(include/drm/intel/pciids.h) and the amdgpu PCI ID table
(drivers/gpu/drm/amd/amdgpu/amdgpu_drv.c) - and writes a C header that
says, for a vendor and device ID, which platform or ASIC it is. Only
facts are taken, but the notices of both files go into the output, as
their licences ask. Either a Linux tree, or a directory holding the two
files under their paths with '/' replaced by '_'.
"""
import os
import re
import sys

# Intel platforms by the macro Linux names them with, and their graphics
# generation (display generation where they differ is not needed here).
INTEL_GEN = {
    "I830": 2, "I845G": 2, "I85X": 2, "I865G": 2,
    "I915G": 3, "I915GM": 3, "I945G": 3, "I945GM": 3, "VLV": 7, "PNV": 3,
    "G33": 3, "I965G": 4, "G45": 4, "I965GM": 4, "GM45": 4, "ILK": 5,
    "SNB": 6, "IVB": 7, "HSW": 7, "BDW": 8, "CHV": 8,
    "SKL": 9, "BXT": 9, "GLK": 9, "KBL": 9, "CFL": 9, "WHL": 9, "CML": 9, "AML": 9,
    "CNL": 10, "ICL": 11, "EHL": 11, "JSL": 11,
    "TGL": 12, "RKL": 12, "DG1": 12, "ADLS": 12, "ADLP": 12, "ADLN": 12,
    "RPLS": 12, "RPLP": 12, "RPLU": 12, "DG2": 12, "ATS_M": 12, "ARL": 12, "MTL": 12,
    "LNL": 20, "BMG": 20, "PTL": 30, "WCL": 30, "NVLP": 30, "NVLS": 30, "CRI": 30,
    "I810": 1, "I815": 1, "DG2_D": 12, "PVC": 12,
}

def read(base, rel):
    for p in (os.path.join(base, rel), os.path.join(base, rel.replace("/", "_"))):
        if os.path.exists(p):
            return open(p, encoding="utf-8", errors="replace").read()
    sys.exit("gen_gpu_ids: no %s under %s" % (rel, base))

def notice(text):
    m = re.match(r"\s*/\*(.*?)\*/", text, re.S)
    return m.group(1) if m else ""

def intel(text):
    joined = text.replace("\\\n", " ")
    macros = {}
    for m in re.finditer(r"#define\s+(INTEL_\w+_IDS)\s*\(MACRO__,\s*\.\.\.\)\s*(.*)", joined):
        macros[m.group(1)] = m.group(2)
    refs = {}
    for name, body in macros.items():
        refs[name] = [r for r in re.findall(r"(INTEL_\w+_IDS)\s*\(", body) if r in macros]
    def expand(name, seen=()):
        body = macros[name]
        ids = [int(x, 16) for x in re.findall(r"MACRO__\(\s*(0x[0-9A-Fa-f]+)", body)]
        for r in refs[name]:
            if r not in seen:
                ids += expand(r, seen + (name,))
        return ids
    referenced = {r for rs in refs.values() for r in rs}
    roots = [n for n in macros if n not in referenced]
    table = {}
    for root in roots:
        plat = root[len("INTEL_"):-len("_IDS")]
        for i in expand(root):
            table.setdefault(i, plat)
    return table

def amd(text):
    table = {}
    for m in re.finditer(r"PCI_DEVICE\(0x1002,\s*0x([0-9A-Fa-f]{4})\),\s*\.driver_data\s*=\s*([A-Z0-9_|]+)", text):
        flags = m.group(2).split("|")
        chip = flags[0][len("CHIP_"):]
        table[int(m.group(1), 16)] = (chip, "AMD_IS_APU" in flags)
    m = re.search(r"amdgpu_unsupported_pciidlist\[\]\s*=\s*\{(.*?)\};", text, re.S)
    old = {int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{4})", m.group(1))} if m else set()
    return table, old

def main():
    base = sys.argv[1]
    itext = read(base, "include/drm/intel/pciids.h")
    atext = read(base, "drivers/gpu/drm/amd/amdgpu/amdgpu_drv.c")
    it = intel(itext)
    at, old = amd(atext)

    plats = sorted(set(it.values()))
    chips = sorted({c for c, _ in at.values()})
    out = []
    w = out.append
    w("/* gpu64_ids.h - generated by tools/gen_gpu_ids.py; do not edit.")
    w(" *")
    w(" * Which Intel platform or AMD ASIC a PCI device ID is, taken from two")
    w(" * files of Linux, whose notices follow. */")
    w("")
    w("/* From include/drm/intel/pciids.h:")
    w(notice(itext).rstrip() + " */")
    w("")
    w("/* From drivers/gpu/drm/amd/amdgpu/amdgpu_drv.c:")
    w(notice(atext).rstrip() + " */")
    w("")
    w("#ifndef GPU64_IDS_H")
    w("#define GPU64_IDS_H")
    w("")
    w("#include <stdint.h>")
    w("")
    w("static const struct { const char* name; uint8_t gen; } gpu64_intel_platforms[] = {")
    for p in plats:
        w('    { "%s", %d },' % (p, INTEL_GEN.get(p, 0)))
    w("};")
    w("")
    w("static const struct { uint16_t id; uint8_t platform; } gpu64_intel_ids[] = {")
    for i in sorted(it):
        w("    { 0x%04X, %d },  /* %s */" % (i, plats.index(it[i]), it[i]))
    w("};")
    w("")
    w("static const char* const gpu64_amd_chips[] = {")
    for c in chips:
        w('    "%s",' % c)
    w("};")
    w("")
    w("/* apu: an AMD_IS_APU part - the GPU of a laptop or desktop processor. */")
    w("static const struct { uint16_t id; uint8_t chip; uint8_t apu; } gpu64_amd_ids[] = {")
    for i in sorted(at):
        c, apu = at[i]
        w("    { 0x%04X, %d, %d },  /* %s */" % (i, chips.index(c), 1 if apu else 0, c))
    w("};")
    w("")
    w("/* Older ATI/AMD parts amdgpu declines: radeon's, or older still. */")
    w("static const uint16_t gpu64_amd_old_ids[] = {")
    for i in sorted(old):
        w("    0x%04X," % i)
    w("};")
    w("")
    w("#endif")
    print("\n".join(out))
    sys.stderr.write("gen_gpu_ids: %d Intel IDs on %d platforms, %d AMD IDs on %d ASICs, %d older\n"
                     % (len(it), len(plats), len(at), len(chips), len(old)))

main()
