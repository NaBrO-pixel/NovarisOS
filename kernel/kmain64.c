/* --- what the handlers below record ---------------------------------- */
static volatile int      bp_hits;
static volatile uint64_t bp_rip;

static volatile int      pf_hits;
static volatile uint64_t pf_cr2;
static volatile uint64_t pf_err;
static volatile uint64_t pf_resume_rip;

static void breakpoint_handler(registers64_t* r) {
    bp_hits++;
    bp_rip = r->rip;
    /* #BP is a trap: rip already points past the int3, so returning
     * unchanged resumes at the next instruction. */
}

static volatile uint64_t timer_ticks;

static void timer_handler(registers64_t* r) {
    (void)r;
    timer_ticks++;
}

/* The same interrupt, once there is something to schedule. */
static void sched_timer_handler(registers64_t* r) {
    timer_ticks++;
    sched64_tick(r);
}

/* Once a real program is running, a page fault is a fact to be reported
 * rather than something to resume past. Without this the handler below
 * sends a ring-3 fault to a *kernel* recovery address, which faults
 * immediately, forever - a silent hang with nothing on the serial port,
 * which is exactly how the first attempt at running glibc presented. */
static volatile int pf_diagnose;
static volatile uint64_t pf_killed;

/* syscall64.s */
extern void enter_user_mode64_abort(void) __attribute__((noreturn));

static uint64_t cow_breaks;

static void page_fault_handler(registers64_t* r) {
    pf_hits++;
    pf_cr2 = read_cr2();
    pf_err = r->err_code;

    /* A write to a page fork shared (Milestone 69). First, and before
     * the diagnostic and the signal both: this is not an error, it is
     * the mechanism, and it happens on perfectly ordinary writes to
     * perfectly ordinary memory.
     *
     * Bit 0 of the error code is "the page was present" and bit 1 is
     * "it was a write". A copy-on-write fault is always both - the page
     * is there and readable, and only the write is refused. Bit 2 says
     * whether ring 3 or the kernel did it, and it is deliberately not
     * checked: with CR0.WP set the kernel faults on these too, which is
     * the whole reason WP is on.
     *
     * break_cow returns 0 for a page that was not shared, so a genuine
     * write to genuinely read-only memory still falls through to
     * everything below. */
    if ((r->err_code & 0x3) == 0x3 && vmspace64_break_cow(pf_cr2)) {
        cow_breaks++;
        return;
    }

    /* A ring-3 fault with a handler installed is the program's business,
     * not a kernel failure - it is how Wine turns a bad access into a
     * Windows exception. Tried before the diagnostic below, so that a
     * fault with no handler still reports rather than vanishing. */
    if (signal64_deliver(SIG64_SEGV, r, pf_cr2)) return;

    if (pf_diagnose) {
        serial64_puts("\nNOVARIS64: *** page fault in the program\n");
        serial64_puts("NOVARIS64:   cr2=");  serial64_puthex(pf_cr2);
        serial64_puts(" rip=");              serial64_puthex(r->rip);
        serial64_puts("\nNOVARIS64:   err="); serial64_puthex(pf_err);
        serial64_puts(" cs=");               serial64_puthex(r->cs);
        serial64_puts(" rsp=");              serial64_puthex(r->rsp);
        /* The registers matter as much as the address: a fault reading
         * through a pointer says nothing until you can see which
         * pointer, and where it came from. */
        serial64_puts("\nNOVARIS64:   rax="); serial64_puthex(r->rax);
        serial64_puts(" rbx=");              serial64_puthex(r->rbx);
        serial64_puts(" rdi=");              serial64_puthex(r->rdi);
        serial64_puts("\nNOVARIS64:   rsi="); serial64_puthex(r->rsi);
        serial64_puts(" rbp=");              serial64_puthex(r->rbp);
        serial64_putc('\n');

        /* A ring-3 fault with nobody to catch it kills the program, the
         * way a real kernel does - 128 + SIGSEGV, which is the status a
         * shell reports. Halting instead would be right for a test
         * asserting nothing faults, and useless for one whose purpose
         * is to find out how far a program gets. */
        if ((r->cs & 3) == 3) {
            pf_killed++;
            syscall64_set_exit_code(139);
            enter_user_mode64_abort();          /* never returns */
        }

        serial64_puts("NOVARIS64: *** halted (the fault was in the kernel)\n");
        for (;;) __asm__ __volatile__("cli; hlt");
    }
    /* #PF is a fault: rip points *at* the instruction that faulted, so
     * returning unchanged would re-run it and fault forever. Send
     * execution to the recovery label instead. */
    r->rip = pf_resume_rip;
}

void kernel_main(uint32_t magic, void* mbi) {
    uint64_t cr0, cr4, efer, rip;
    uint64_t before, after, probed;

    serial64_init();

    /* CR0.WP, before anything maps a page read-only (Milestone 69).
     *
     * Without it the write-protect bit in a PTE binds ring 3 only, and
     * the kernel writes straight through a read-only mapping. That is
     * survivable until copy-on-write exists and silently wrong the
     * moment it does: a read() into a forked child's buffer, or an
     * argv copied onto its stack, would be written by the kernel into
     * the page the *parent* is still using, with no fault and no way to
     * notice. Setting it makes one fault path serve both rings.
     *
     * GRUB leaves it clear and boot64.s only ever touched the low 16
     * bits of CR0, so nothing before this line had it on. */
    __asm__ __volatile__("mov %%cr0, %%rax\n\t"
                         "or  $(1 << 16), %%rax\n\t"
                         "mov %%rax, %%cr0"
                         ::: "rax", "memory");

    cr0  = read_cr0();
    cr4  = read_cr4();
    efer = read_msr(0xC0000080);
    __asm__ __volatile__("lea (%%rip), %0" : "=r"(rip));

    serial64_puts("\nNOVARIS64: ---- long mode bring-up ----\n");

    /* --- layer 1: the mode itself --------------------------------- */
    /* EFER.LMA is set by the CPU when long mode actually goes active. It
     * is the one bit here that is proof rather than assertion. */
    check("EFER.LMA  - long mode is active", (efer & (1ULL << 10)) != 0);
    check("EFER.LME  - long mode is enabled", (efer & (1ULL << 8)) != 0);
    check("CR0.PG    - paging is on",         (cr0 & (1ULL << 31)) != 0);
    check("CR4.PAE   - PAE is on",            (cr4 & (1ULL << 5)) != 0);
    check("CR4.OSFXSR- SSE is usable",        (cr4 & (1ULL << 9)) != 0);
    check("pointers are 8 bytes",             sizeof(void*) == 8);
    check("long is 8 bytes (LP64)",           sizeof(long) == 8);
    check("RIP is in the higher half",        rip >= 0xFFFFFFFF80000000ULL);
    check("multiboot magic is 0x2BADB002",    magic == 0x2BADB002u);
    check("multiboot info pointer is non-NULL", mbi != 0);

    serial64_puts("NOVARIS64: cs      = "); serial64_puthex(read_cs());
    serial64_puts("\nNOVARIS64: rip     = "); serial64_puthex(rip);
    serial64_puts("\nNOVARIS64: cr3     = "); serial64_puthex(read_cr3());
    serial64_puts("\nNOVARIS64: efer    = "); serial64_puthex(efer);
    serial64_puts("\nNOVARIS64: kernel  = ");
    serial64_puthex((uint64_t)_kernel_virtual_start);
    serial64_puts(" .. ");
    serial64_puthex((uint64_t)_kernel_virtual_end);
    serial64_puts("\nNOVARIS64: size    = ");
    serial64_putdec((uint64_t)(_kernel_virtual_end - _kernel_virtual_start));
    serial64_puts(" bytes\n");

    /* --- layer 2: descriptors -------------------------------------- */
    serial64_puts("NOVARIS64: -- descriptors --\n");
    gdt64_install();

    /* Surviving gdt64_flush at all is most of the test: it reloads every
     * segment register and changes cs through a far return, so a wrong
     * descriptor here is a fault rather than a wrong answer. */
    check("GDT loaded, cs is the kernel code selector",
          read_cs() == GDT64_KCODE_SEL);
    check("TSS loaded into the task register",
          read_tr() == GDT64_TSS_SEL);
    check("IST1 (double fault) stack is set",
          gdt64_ist_stack(IST_DOUBLE_FAULT) != 0);
    check("IST2 (NMI) stack is set",
          gdt64_ist_stack(IST_NMI) != 0);

    /* --- layer 3: an interrupt, taken and returned from ------------- */
    serial64_puts("NOVARIS64: -- interrupts --\n");
    idt64_install();
    register_interrupt_handler64(3,  breakpoint_handler);
    register_interrupt_handler64(14, page_fault_handler);

    /* Registers either side of an int3. If the stub's fifteen pushes and
     * pops are not exact mirrors, this is where it shows: a value lands
     * back in the wrong register and the comparison fails. */
    before = 0x0123456789ABCDEFULL;
    __asm__ __volatile__(
        "mov %1, %%r12\n\t"
        "int $3\n\t"
        "mov %%r12, %0"
        : "=r"(after)
        : "r"(before)
        : "r12");

    check("int3 reached a C handler", bp_hits == 1);
    check("execution resumed after int3", 1);
    check("a callee-saved register survived the interrupt", after == before);
    check("the saved rip was in the kernel", bp_rip >= 0xFFFFFFFF80000000ULL);

    /* --- layer 4: a handler that rewrites the frame ----------------- */
    /* 0xFFFF800000000000 is canonical but has no PML4 entry, so reading it
     * is a page fault at a known address. probe_read64 is the faulting
     * instruction and probe_read64_recover is where the handler sends
     * execution instead - both real symbols, for the reason isr64.s
     * explains at length. */
    pf_resume_rip = (uint64_t)&probe_read64_recover;
    probed = probe_read64((const void*)0xFFFF800000000000ULL);

    check("the probe returned the recovery value, not the memory", probed == 0);
    check("a page fault reached a C handler", pf_hits == 1);
    check("cr2 held the address that faulted",
          pf_cr2 == 0xFFFF800000000000ULL);
    check("the fault was a not-present read",
          (pf_err & 0x1) == 0);
    check("the handler rewrote rip and execution resumed there", 1);

    serial64_puts("NOVARIS64: cr2     = "); serial64_puthex(pf_cr2);
    serial64_puts("\nNOVARIS64: pf err  = "); serial64_puthex(pf_err);
    serial64_putc('\n');

    /* --- layer 5: physical frames ---------------------------------- */
    serial64_puts("NOVARIS64: -- physical memory --\n");
    {
        uint64_t kphys_start = (uint64_t)_kernel_physical_start;
        uint64_t kphys_end   = (uint64_t)_kernel_physical_end;
        uint64_t total, free_before, f1, f2, free_after, dbl;

        pmm64_init((const multiboot_info_t*)mbi, kphys_start, kphys_end);

        /* Immediately after, and before anything allocates: the initrd
         * sits in RAM the allocator was just told is free. */
        initrd64_reserve((const multiboot_info_t*)mbi);

        /* Paging and the direct map come up here rather than in layer 6
         * below, because reading the archive needs the direct map and
         * building the direct map needs the frame allocator - so the
         * three have exactly one legal order. Layer 6 still tests them;
         * it just no longer starts them. */
        paging64_init();
        paging64_physmap_init(pmm64_highest_addr());

        initrd64_init((const multiboot_info_t*)mbi);

        /* There is always a current process from here on. Everything
         * that used to be a kernel-wide static - open files, the heap,
         * the path /proc/self/exe answers with - now lives in one, so a
         * syscall arriving with no process is a null dereference in the
         * kernel rather than a missing feature. */
        proc64_init();
        proc64_set_current(proc64_create());

        check("the frame allocator came up", pmm64_ready());
        total = pmm64_total_frames();
        free_before = pmm64_free_frames();
        check("RAM was found", total > 0);
        check("some of it is free", free_before > 0);
        check("not all of it is free", free_before < total);

        f1 = pmm64_alloc_frame();
        f2 = pmm64_alloc_frame();
        check("a frame was allocated", f1 != 0);
        check("a second frame was allocated", f2 != 0);
        check("the two are different frames", f1 != f2);
        check("frames are page aligned", (f1 % PMM64_FRAME_SIZE) == 0);
        /* The first megabyte and the kernel's own image are the two things
         * that must never be handed out; a bug in the reserve pass shows
         * up here rather than as corruption three milestones later. */
        check("no frame comes from the first megabyte", f1 >= 0x100000ULL);
        check("no frame overlaps the kernel image",
              f1 < kphys_start || f1 >= kphys_end);
        check("no frame overlaps the frame bitmap",
              f1 < pmm64_bitmap_phys() ||
              f1 >= pmm64_bitmap_phys() + pmm64_bitmap_bytes());

        check("allocating two frames used two frames",
              pmm64_free_frames() == free_before - 2);
        pmm64_free_frame(f1);
        pmm64_free_frame(f2);
        free_after = pmm64_free_frames();
        check("freeing them gave both back", free_after == free_before);

        /* Freeing twice is the one error this allocator is asked to
         * notice rather than obey. */
        dbl = pmm64_double_frees();
        pmm64_free_frame(f1);
        check("a double free was counted, not obeyed",
              pmm64_double_frees() == dbl + 1);
        check("and it did not change the free count",
              pmm64_free_frames() == free_after);

        serial64_puts("NOVARIS64: ram top = ");
        serial64_puthex(pmm64_highest_addr());
        serial64_puts("\nNOVARIS64: frames  = ");
        serial64_putdec(total);
        serial64_puts(" total, ");
        serial64_putdec(free_before);
        serial64_puts(" free\n");
        serial64_puts("NOVARIS64: bitmap  = ");
        serial64_puthex(pmm64_bitmap_phys());
        serial64_puts(" .. +");
        serial64_putdec(pmm64_bitmap_bytes());
        serial64_puts(" bytes\n");
    }

    /* --- layer 6: four-level paging --------------------------------- */
    serial64_puts("NOVARIS64: -- paging --\n");
    {
        /* PML4 slot 384. Not 256: that is the address layer 4 above
         * relies on being unmapped, and mapping it here would quietly
         * turn that page-fault test into a test of nothing. */
        const uint64_t TEST_VA = 0xFFFFC00000000000ULL;
        const uint64_t MAGIC   = 0x00C0FFEE5EA51DE5ULL;
        uint64_t frame, got, tables_before;
        volatile uint64_t* p;
        int rc;

        /* paging64_init and paging64_physmap_init already ran, in layer
         * 5 - see the note there. */

        /* The self-reference, read through itself: if the recursive
         * address were wrong this load would fault rather than answer. */
        {
            uint64_t* pml4 = paging64_pml4();
            check("the PML4 can be read through its own recursive slot",
                  (pml4[510] & 1) != 0);
            check("the higher half is still mapped in it",
                  (pml4[511] & 1) != 0);
            check("the recursive slot points at the PML4 itself",
                  (pml4[510] & 0x000FFFFFFFFFF000ULL) ==
                  (read_cr3() & 0x000FFFFFFFFFF000ULL));
        }

        tables_before = paging64_tables_allocated();
        frame = pmm64_alloc_frame();
        check("a frame to map was allocated", frame != 0);

        rc = paging64_map(TEST_VA, frame, PAGE64_PRESENT | PAGE64_WRITE);
        check("a fresh 4KB page mapped", rc == PAGING64_OK);
        /* An empty PML4 slot needs a PDPT, a PD and a PT built under it. */
        check("three intermediate tables were built",
              paging64_tables_allocated() == tables_before + 3);

        p = (volatile uint64_t*)TEST_VA;
        *p = MAGIC;
        check("the mapped page is writable and reads back",
              *p == MAGIC);

        rc = paging64_translate(TEST_VA, &got);
        check("translate resolved the mapping", rc == PAGING64_OK);
        check("and resolved it to the frame that was mapped", got == frame);

        /* The strongest form of the same question: the bytes written
         * through the new virtual address must be visible at that
         * physical frame's other address. A mapping that merely does not
         * fault would pass everything above and fail this. */
        {
            volatile uint64_t* through_phys =
                (volatile uint64_t*)phys64_to_virt(frame);
            check("the write landed in that physical frame",
                  *through_phys == MAGIC);
        }

        check("an offset inside the page translates with its offset",
              paging64_translate(TEST_VA + 0x123, &got) == PAGING64_OK &&
              got == frame + 0x123);

        /* The kernel's own text is inside a 2MB page boot64.s built.
         * Refusing to map over it is the honest answer while splitting
         * huge pages is unimplemented. */
        check("mapping over a 2MB page is refused, not corrupted",
              paging64_map(0xFFFFFFFF80000000ULL, frame,
                           PAGE64_PRESENT | PAGE64_WRITE)
              == PAGING64_HUGE_IN_WAY);

        check("an unmapped address does not translate",
              paging64_translate(0xFFFFC00000200000ULL, &got)
              == PAGING64_NOT_MAPPED);

        /* And unmapping must genuinely remove it - checked by faulting on
         * it, using the same probe/recover pair as layer 4. */
        rc = paging64_unmap(TEST_VA);
        check("the page unmapped", rc == PAGING64_OK);
        check("it no longer translates",
              paging64_translate(TEST_VA, &got) == PAGING64_NOT_MAPPED);

        pf_hits = 0;
        pf_resume_rip = (uint64_t)&probe_read64_recover;
        probe_read64((const void*)TEST_VA);
        check("reading it now faults", pf_hits == 1);
        check("and it faulted at that address", pf_cr2 == TEST_VA);

        check("unmapping it twice is refused",
              paging64_unmap(TEST_VA) == PAGING64_NOT_MAPPED);

        pmm64_free_frame(frame);

        serial64_puts("NOVARIS64: tables  = ");
        serial64_putdec(paging64_tables_allocated());
        serial64_puts(" allocated\n");
    }

    /* --- layer 6b: the direct map (Milestone 66) --------------------- */
    serial64_puts("NOVARIS64: -- direct map --\n");
    {
        const uint64_t BOOT_WINDOW = 0x40000000ULL;   /* what boot64.s maps */
        const uint64_t MAGIC = 0x00D15EA5EB0A7ULL;
        uint64_t mapped = paging64_physmap_bytes();
        uint64_t high, got;

        check("the direct map covers memory", mapped > 0);
        check("it covers all the RAM that was found",
              mapped >= pmm64_highest_addr());

        /* The kernel image is at a known physical address and its first
         * bytes are the multiboot header, so the direct map can be checked
         * against something whose value is not of this test's choosing. */
        {
            uint64_t kphys = (uint64_t)_kernel_physical_start;
            const uint32_t* via_boot =
                (const uint32_t*)(0xFFFFFFFF80000000ULL + kphys);
            const uint32_t* via_map = (const uint32_t*)phys64_to_virt(kphys);
            check("the direct map and the boot window agree on the kernel",
                  *via_map == *via_boot);
        }

        check("a 2MB page translates through the direct map",
              paging64_translate(PHYSMAP64_BASE + 0x100000ULL, &got)
              == PAGING64_OK && got == 0x100000ULL);

        /* The ceiling itself. A frame above the boot window is unreachable
         * through KERNEL_VMA by construction - before this milestone the
         * kernel could not have written this line. */
        high = pmm64_alloc_above(BOOT_WINDOW);
        if (!high) {
            /* Under 1GB of RAM: the wall cannot be demonstrated, and
             * saying so beats a test that passes by not running. */
            serial64_puts("NOVARIS64: SKIP  no RAM above 1GB to test with\n");
        } else {
            volatile uint64_t* p = (volatile uint64_t*)phys64_to_virt(high);

            check("a frame above the old 1GB ceiling was allocated",
                  high >= BOOT_WINDOW);
            *p = MAGIC;
            check("the kernel can write to it through the direct map",
                  *p == MAGIC);

            /* And that it is genuinely that frame, not an aliased one:
             * mapped a second time at a scratch address, the same bytes
             * must appear. */
            {
                const uint64_t SCRATCH = 0xFFFFC00000400000ULL;
                check("it maps at a second address",
                      paging64_map(SCRATCH, high,
                                   PAGE64_PRESENT | PAGE64_WRITE)
                      == PAGING64_OK);
                check("and the same bytes are there",
                      *(volatile uint64_t*)SCRATCH == MAGIC);
                *(volatile uint64_t*)SCRATCH = ~MAGIC;
                check("a write through one address is seen at the other",
                      *p == ~MAGIC);
                paging64_unmap(SCRATCH);
            }

            pmm64_free_frame(high);
        }

        serial64_puts("NOVARIS64: physmap = ");
        serial64_putdec(mapped / (1024 * 1024));
        serial64_puts(" MB at ");
        serial64_puthex(PHYSMAP64_BASE);
        serial64_putc('\n');
    }

    /* --- layer 6c: the framebuffer (Milestone 67) -------------------- */
    serial64_puts("NOVARIS64: -- framebuffer --\n");
    {
        const multiboot_info_t* m = (const multiboot_info_t*)mbi;
        int rc = fb64_init(m);

        if (rc != FB64_OK) {
            /* A headless boot is a legitimate configuration, so it is
             * reported rather than failed - but it is reported loudly,
             * because a display test that silently tests nothing is how
             * a driver rots. */
            serial64_puts("NOVARIS64: SKIP  no usable framebuffer, rc = ");
            serial64_putdec((uint64_t)(-rc));
            serial64_putc('\n');
        } else {
            const uint32_t RED   = 0xFF0000, GREEN = 0x00FF00;
            const uint32_t BLUE  = 0x0000FF, WHITE = 0xFFFFFF;
            const uint32_t BG    = 0x102030;

            check("the framebuffer came up", fb64_ready());
            check("its geometry is the one the bootloader granted",
                  fb64_width()  == m->framebuffer_width &&
                  fb64_height() == m->framebuffer_height &&
                  fb64_bpp()    == m->framebuffer_bpp);
            check("it is at the physical address the bootloader named",
                  fb64_phys() == m->framebuffer_addr);
            /* A pitch shorter than a row of pixels would mean every
             * scanline after the first is drawn in the wrong place. */
            check("a scanline is at least as wide as the picture",
                  fb64_pitch() >= fb64_width() * (fb64_bpp() / 8));

            /* The round trip that proves the mapping. This reads back
             * through an uncacheable mapping of a device that is not
             * RAM, so a value that survives it really did reach VRAM -
             * a stray mapping over ordinary memory would pass every
             * assertion above and fail this one only by accident, which
             * is why the colours are distinct rather than 0 and 1. */
            fb64_put_pixel(0, 0, RED);
            fb64_put_pixel(1, 0, GREEN);
            fb64_put_pixel(0, 1, BLUE);
            check("a pixel written to VRAM reads back",
                  fb64_get_pixel(0, 0) == RED);
            check("and its neighbour is not the same pixel",
                  fb64_get_pixel(1, 0) == GREEN);
            check("nor is the one on the next scanline",
                  fb64_get_pixel(0, 1) == BLUE);

            /* Reading outside the screen. This says only that
             * fb64_get_pixel clamps, which is worth one line and is not
             * a test of anything that writes. */
            check("reading outside the screen answers 0, not memory",
                  fb64_get_pixel(fb64_width(), 0) == 0);

            /* Writing outside it, which is the one that matters - and
             * which needs an observable consequence rather than a
             * clamped read.
             *
             * The first version of this asked get_pixel about the
             * out-of-bounds coordinate and asserted 0. That passes with
             * the bounds check deleted, because get_pixel clamps too:
             * the assertion was reading a different function's clip.
             * Deleting the check and watching the test still pass is
             * how it was found.
             *
             * With a scanline exactly one row of pixels wide, an
             * unclipped store at (width, 0) computes the address of
             * (0, 1) - so a known value there turns "wrote out of
             * bounds" into something visible. Guarded on that equality
             * rather than assumed, since a padded pitch would put the
             * stray write in the padding where nothing can see it. */
            if (fb64_pitch() == fb64_width() * (fb64_bpp() / 8)) {
                fb64_put_pixel(0, 1, BLUE);
                fb64_put_pixel(fb64_width(), 0, WHITE);
                check("a write past the right edge does not land on the "
                      "next row",
                      fb64_get_pixel(0, 1) == BLUE);

                /* The same question for a rectangle: 64 wide starting 4
                 * from the edge, so 60 of it is off-screen and would
                 * wrap onto row 5 if the clip trimmed nothing. */
                fb64_fill_rect(fb64_width() - 4, 4, 64, 1, WHITE);
                check("a rectangle running off the right edge is trimmed, "
                      "not wrapped",
                      fb64_get_pixel(0, 5) != WHITE);
                check("and the part of it that is on screen was drawn",
                      fb64_get_pixel(fb64_width() - 1, 4) == WHITE);
            }

            /* Past the bottom edge. Nothing can observe where an
             * unclipped store would land - it is beyond the last
             * scanline, inside the 2MB-rounded mapping - so this asserts
             * only that the machine is still running afterwards, which
             * every check below it does implicitly. */
            fb64_put_pixel(0, fb64_height(), WHITE);

            {
                /* One blit, from a surface in RAM to a device above RAM
                 * - which is the whole shape of what a compositor does,
                 * and needs the direct map and the MMIO map to be two
                 * different things that both work. */
                static uint32_t tile[4 * 4];
                int i;
                for (i = 0; i < 16; i++) tile[i] = (i & 1) ? WHITE : RED;
                fb64_blit(100, 100, 4, 4, tile, 4);
                check("a blit from RAM landed in VRAM",
                      fb64_get_pixel(100, 100) == RED &&
                      fb64_get_pixel(101, 100) == WHITE);
            }

            /* The picture the host checks with a screenshot. Drawn last
             * so nothing above overwrites it, and in flat colours at
             * known coordinates so that verifying it is a pixel compare
             * rather than a judgement.
             *
             * The coordinates are fixed, so they are guarded rather than
             * assumed: everything above this point works at any
             * geometry the bootloader hands over, and only the pattern
             * needs a screen at least as big as the one boot64.s asks
             * for. A smaller mode says so instead of failing. */
            if (fb64_width() >= 1024 && fb64_height() >= 768) {
                fb64_clear(BG);
                fb64_fill_rect(100, 100, 200, 200, RED);
                fb64_fill_rect(400, 100, 200, 200, GREEN);
                fb64_fill_rect(100, 400, 200, 200, BLUE);
                fb64_fill_rect(400, 400, 200, 200, WHITE);

                check("the test pattern is on the screen",
                      fb64_get_pixel(200, 200) == RED   &&
                      fb64_get_pixel(500, 200) == GREEN &&
                      fb64_get_pixel(200, 500) == BLUE  &&
                      fb64_get_pixel(500, 500) == WHITE &&
                      fb64_get_pixel(800, 700) == BG);
            } else {
                serial64_puts("NOVARIS64: SKIP  screen too small for the "
                              "test pattern\n");
            }

            serial64_puts("NOVARIS64: screen  = ");
            serial64_putdec(fb64_width());
            serial64_putc('x');
            serial64_putdec(fb64_height());
            serial64_putc('x');
            serial64_putdec(fb64_bpp());
            serial64_puts(" at ");
            serial64_puthex(fb64_phys());
            serial64_puts(", pitch ");
            serial64_putdec(fb64_pitch());
            serial64_puts("\nNOVARIS64: drawn   = ");
            serial64_putdec(fb64_pixels_written());
            serial64_puts(" pixels\n");
        }
    }

    /* --- layer 7: the kernel heap ----------------------------------- */
    serial64_puts("NOVARIS64: -- heap --\n");
    {
        const uint64_t PATTERN = 0xA5A5A5A5DEADBEEFULL;
        uint8_t *a, *b, *p1, *p2, *p3;
        uint64_t used, total, blocks_before, blocks_after, dbl;

        kheap64_init();

        a = (uint8_t*)kmalloc64(64);
        check("kmalloc returned memory", a != 0);
        check("and it is 16-byte aligned", ((uint64_t)a % KHEAP64_ALIGN) == 0);

        *(volatile uint64_t*)a = PATTERN;
        check("the allocation is writable and reads back",
              *(volatile uint64_t*)a == PATTERN);

        b = (uint8_t*)kmalloc64(64);
        check("a second allocation succeeded", b != 0);
        check("the two do not overlap", b >= a + 64 || a >= b + 64);
        /* 32 bytes of header + a 64-byte payload: the next block starts
         * 96 bytes on. Asserting the exact layout is what makes the
         * coalescing test below mean anything. */
        check("blocks are laid out end to end", b == a + 96);

        kheap64_stats(&used, &total);
        check("stats report memory in use", used > 0);
        check("stats report at least the initial heap mapped",
              total >= KHEAP64_INITIAL - PAGE64_SIZE);

        kfree64(a);
        kfree64(b);

        dbl = kheap64_double_frees();
        kfree64(a);
        check("a double free was counted, not obeyed",
              kheap64_double_frees() == dbl + 1);

        /* Coalescing, observed rather than asserted by the allocator
         * about itself: three adjacent blocks freed have to collapse back
         * into the block they were carved from, leaving the free list
         * exactly as long as it was before. An allocator that only marks
         * blocks unused would leave three more. */
        blocks_before = kheap64_free_blocks();
        p1 = (uint8_t*)kmalloc64(64);
        p2 = (uint8_t*)kmalloc64(64);
        p3 = (uint8_t*)kmalloc64(64);
        check("three consecutive blocks are adjacent",
              p2 == p1 + 96 && p3 == p2 + 96);
        kfree64(p2);
        kfree64(p1);
        kfree64(p3);
        blocks_after = kheap64_free_blocks();
        check("freeing them merged them back into one block",
              blocks_after == blocks_before);

        /* Bigger than the initial heap, so the growth path runs. */
        {
            uint8_t* big = (uint8_t*)kmalloc64(128 * 1024);
            check("an allocation larger than the heap grew it", big != 0);
            if (big) {
                big[0] = 1;
                big[128 * 1024 - 1] = 2;
                check("the far end of a grown allocation is mapped",
                      big[0] == 1 && big[128 * 1024 - 1] == 2);
                kfree64(big);
            }
        }

        /* The point of the rewrite. kheap.c walks every block, used or
         * free, so N allocations cost N^2/2 steps - 500,000 at N=1000.
         * Walking only the free list makes it linear. The bound below is
         * deliberately loose; what it rules out is the quadratic term. */
        {
            const uint64_t N = 1000;
            uint64_t steps0, calls0, steps1, calls1;
            void** ptrs = (void**)kmalloc64(N * sizeof(void*));

            check("room for the pointer array", ptrs != 0);
            if (ptrs) {
                kheap64_walk_stats(&steps0, &calls0);
                for (uint64_t i = 0; i < N; i++) ptrs[i] = kmalloc64(32);
                kheap64_walk_stats(&steps1, &calls1);

                check("every allocation in the run succeeded",
                      ptrs[0] != 0 && ptrs[N - 1] != 0);
                check("the run made N calls", calls1 - calls0 == N);
                check("the allocator is linear, not quadratic",
                      steps1 - steps0 < N * 8);

                serial64_puts("NOVARIS64: walk    = ");
                serial64_putdec(steps1 - steps0);
                serial64_puts(" steps for ");
                serial64_putdec(N);
                serial64_puts(" allocations (quadratic would be ~");
                serial64_putdec(N * N / 2);
                serial64_puts(")\n");

                for (uint64_t i = 0; i < N; i++) kfree64(ptrs[i]);
                kfree64(ptrs);
            }
        }

        kheap64_stats(&used, &total);
        serial64_puts("NOVARIS64: heap    = ");
        serial64_putdec(used);
        serial64_puts(" used / ");
        serial64_putdec(total);
        serial64_puts(" mapped, ");
        serial64_putdec(kheap64_free_blocks());
        serial64_puts(" free blocks\n");
    }

    /* --- layer 8: kstring, on a 64-bit target ----------------------- */
    /* kstring.c is now shared with the 32-bit tree rather than forked:
     * its size parameters became size_t, which is the same type on i386
     * and the right one here. These check that the shared file behaves on
     * this target - kstrlen in particular now returns size_t. */
    serial64_puts("NOVARIS64: -- kstring --\n");
    {
        char buf[64];
        const char* src = "novaris";

        check("kstrlen counts", kstrlen(src) == 7);
        check("kstrlen returns a 64-bit size_t here",
              sizeof(kstrlen(src)) == 8);

        kmemset(buf, 0, sizeof(buf));
        kmemcpy(buf, src, 8);
        check("kmemcpy copied", kstrcmp(buf, "novaris") == 0);
        check("kmemcmp agrees", kmemcmp(buf, src, 8) == 0);

        kstrlcpy(buf, "truncate me", 6);
        check("kstrlcpy bounds and terminates",
              kstrcmp(buf, "trunc") == 0);

        /* kdiv64 uses a 32-bit DIV, which is legal in long mode. It is
         * only needed on i386, where a 64-bit divide would call libgcc,
         * but it has to still be correct if it is going to be compiled. */
        {
            uint32_t rem = 0;
            uint64_t q = kdiv64(1000000007ULL, 1000U, &rem);
            check("kdiv64 divides", q == 1000000ULL && rem == 7U);
        }
    }

    /* --- layer 9: an IRQ that lands where the IDT expects ----------- */
    /* This is the layer that found the bug. The IDT has always installed
     * its IRQ gates at 32-47, but nothing remapped the 8259s, so the
     * hardware was still delivering IRQ0 to vector 8 - which is #DF. No
     * previous milestone noticed because none of them ever set IF. */
    serial64_puts("NOVARIS64: -- timer --\n");
    {
        const uint32_t divisor = 1193182u / 1000u;   /* ~1kHz */
        uint64_t spins;

        register_interrupt_handler64(32, timer_handler);

        outb(0x43, 0x36);                    /* channel 0, lo/hi, mode 3 */
        outb(0x40, (uint8_t)(divisor & 0xFF));
        outb(0x40, (uint8_t)(divisor >> 8));

        idt64_irq_set_mask(0, 0);
        __asm__ __volatile__("sti");

        /* Bounded, so a machine where this never arrives fails the test
         * rather than hanging until the harness kills it. */
        for (spins = 0; spins < 50000000ULL && timer_ticks < 3; spins++)
            __asm__ __volatile__("pause");

        __asm__ __volatile__("cli");

        check("the timer interrupt arrived at vector 32", timer_ticks >= 3);
        /* If the remap had not happened, the first tick would have been
         * taken as #DF and the machine would already have halted, so
         * reaching this line at all is half the result. */
        check("the machine survived taking interrupts",
              spins < 50000000ULL);

        /* Masked again before ring 3 below, so that test is deterministic
         * rather than depending on whether a tick happens to land inside
         * its few microseconds. Taking an interrupt *while in ring 3* is
         * a different path - it switches to the TSS's rsp0 - and it is
         * not exercised yet; the scheduler in item 3 is what will need
         * it and what should test it. */
        idt64_irq_set_mask(0, 1);

        serial64_puts("NOVARIS64: ticks   = ");
        serial64_putdec(timer_ticks);
        serial64_putc('\n');
    }

    /* --- layer 10: ring 3, and a syscall that comes back ------------ */
    serial64_puts("NOVARIS64: -- ring 3 --\n");
    {
        /* PML4 slot 224. Not one of the low addresses: slot 0 is still
         * the boot identity map, built from 2MB pages, so anything under
         * a gigabyte would come back HUGE_IN_WAY. */
        const uint64_t UCODE_VA  = 0x0000700000000000ULL;
        const uint64_t USTACK_VA = 0x0000700000010000ULL;
        uint64_t code_frame, stack_frame, code_len;
        int rc_code, rc_stack;

        code_len = (uint64_t)(user_test_code_end - user_test_code);
        check("the ring-3 program fits in a page",
              code_len > 0 && code_len < PAGE64_SIZE);

        /* An interrupt taken in ring 3 switches to the stack in the TSS.
         * Without this the first one triple-faults, and it would be the
         * timer rather than anything this test does. */
        gdt64_set_kernel_stack((uint64_t)&ring3_int_stack[sizeof(ring3_int_stack)]);
        syscall64_init();

        code_frame  = pmm64_alloc_frame();
        stack_frame = pmm64_alloc_frame();
        check("frames for the program and its stack",
              code_frame != 0 && stack_frame != 0);

        /* Copied through the physical window rather than through the
         * user mapping, so the code page never has to be writable. */
        kmemcpy((void*)(0xFFFFFFFF80000000ULL + code_frame),
                user_test_code, code_len);

        rc_code  = paging64_map(UCODE_VA, code_frame,
                                PAGE64_PRESENT | PAGE64_USER);
        rc_stack = paging64_map(USTACK_VA, stack_frame,
                                PAGE64_PRESENT | PAGE64_WRITE | PAGE64_USER);
        check("the program mapped as user-readable", rc_code == PAGING64_OK);
        check("its stack mapped as user-writable", rc_stack == PAGING64_OK);

        /* Everything above this line is setup. This is the line that
         * either returns or hangs the machine. */
        enter_user_mode64(UCODE_VA, USTACK_VA + PAGE64_SIZE, 0);

        check("ring 3 was entered and returned", syscall64_count() == 2);
        /* The program read its own CS and handed it over. 0x23 is the
         * user code selector with RPL 3, and it is the one value here
         * that ring 0 could not have produced: the same code running at
         * ring 0 would have reported 0x08. */
        check("the program really was at ring 3 (CS = 0x23)",
              syscall64_last_arg() == 0x23);
        /* And it resumed after the first syscall with the value the
         * kernel returned, which is what proves SYSRET went back rather
         * than the program simply never continuing. */
        check("SYSRET returned to ring 3 with the result",
              syscall64_exit_code() == 0x23 + 0x1111);

        serial64_puts("NOVARIS64: user cs = ");
        serial64_puthex(syscall64_last_arg());
        serial64_puts("\nNOVARIS64: exit   = ");
        serial64_puthex(syscall64_exit_code());
        serial64_puts("\nNOVARIS64: calls  = ");
        serial64_putdec(syscall64_count());
        serial64_putc('\n');

        paging64_unmap(UCODE_VA);
        paging64_unmap(USTACK_VA);
        pmm64_free_frame(code_frame);
        pmm64_free_frame(stack_frame);
    }

    /* --- layer 11: two address spaces ------------------------------- */
    serial64_puts("NOVARIS64: -- address spaces --\n");
    {
        /* PML4 slot 192: the low half, so it belongs to the space rather
         * than to the kernel, which is the whole point of the test. */
        const uint64_t VA = 0x0000600000000000ULL;
        const uint64_t VAL_A = 0xAAAAAAAA11111111ULL;
        const uint64_t VAL_B = 0xBBBBBBBB22222222ULL;
        vmspace64_t kspace, warm, a, b;
        uint64_t fa, fb, free_before, free_after, got;

        vmspace64_kernel_space(&kspace);

        /* One space created and destroyed before the frames are counted.
         * The first create maps a scratch page, and the kernel-half page
         * tables that produces are permanent and shared - counting from
         * before them would look like a leak that is not one. */
        if (vmspace64_create(&warm)) vmspace64_destroy(&warm);
        free_before = pmm64_free_frames();

        check("space A was created", vmspace64_create(&a) != 0);
        check("space B was created", vmspace64_create(&b) != 0);
        check("they are distinct spaces", a.pml4_phys != b.pml4_phys);
        check("and neither is the kernel's",
              a.pml4_phys != kspace.pml4_phys &&
              b.pml4_phys != kspace.pml4_phys);

        fa = pmm64_alloc_frame();
        fb = pmm64_alloc_frame();
        check("a frame for each", fa != 0 && fb != 0 && fa != fb);

        check("one address mapped in A",
              vmspace64_map(&a, VA, fa, PAGE64_PRESENT | PAGE64_WRITE)
              == PAGING64_OK);
        check("the same address mapped in B, to a different frame",
              vmspace64_map(&b, VA, fb, PAGE64_PRESENT | PAGE64_WRITE)
              == PAGING64_OK);

        /* The actual question: does one address mean two different things
         * depending on which space is loaded. */
        vmspace64_switch(&a);
        *(volatile uint64_t*)VA = VAL_A;
        vmspace64_switch(&b);
        *(volatile uint64_t*)VA = VAL_B;
        check("B reads back its own value", *(volatile uint64_t*)VA == VAL_B);
        vmspace64_switch(&a);
        check("A still reads its own, at the very same address",
              *(volatile uint64_t*)VA == VAL_A);

        vmspace64_switch(&kspace);
        check("and the address means nothing in the kernel's space",
              paging64_translate(VA, &got) == PAGING64_NOT_MAPPED);

        /* The kernel survived three CR3 loads, which it only can because
         * its half of every space is the same half. */
        {
            void* p = kmalloc64(64);
            check("the kernel still works after switching back", p != 0);
            kfree64(p);
        }

        vmspace64_destroy(&a);
        vmspace64_destroy(&b);
        pmm64_free_frame(fa);
        pmm64_free_frame(fb);

        free_after = pmm64_free_frames();
        check("destroying both spaces gave every frame back",
              free_after == free_before);

        serial64_puts("NOVARIS64: frames  = ");
        serial64_putdec(free_before);
        serial64_puts(" free before, ");
        serial64_putdec(free_after);
        serial64_puts(" after\n");
    }

    /* --- layer 12: a ring-3 program in its own address space -------- */
    /* Layers 10 and 11 separately: ring 3 works, and spaces isolate.
     * This is both at once, which is what a process actually is - user
     * pages that exist only in its own low half, kernel reachable from
     * inside it because the high half is shared. */
    serial64_puts("NOVARIS64: -- a program in its own space --\n");
    {
        const uint64_t UCODE_VA  = 0x0000700000000000ULL;
        const uint64_t USTACK_VA = 0x0000700000010000ULL;
        vmspace64_t kspace, proc;
        uint64_t code_frame, stack_frame, code_len, got;
        uint64_t calls_before = syscall64_count();

        vmspace64_kernel_space(&kspace);
        code_len = (uint64_t)(user_test_code_end - user_test_code);

        check("a space for the program", vmspace64_create(&proc) != 0);
        code_frame  = pmm64_alloc_frame();
        stack_frame = pmm64_alloc_frame();
        check("frames for it", code_frame != 0 && stack_frame != 0);

        kmemcpy((void*)(0xFFFFFFFF80000000ULL + code_frame),
                user_test_code, code_len);

        check("its code mapped into its own space",
              vmspace64_map(&proc, UCODE_VA, code_frame,
                            PAGE64_PRESENT | PAGE64_USER) == PAGING64_OK);
        check("its stack too",
              vmspace64_map(&proc, USTACK_VA, stack_frame,
                            PAGE64_PRESENT | PAGE64_WRITE | PAGE64_USER)
              == PAGING64_OK);

        /* Nothing of the program is visible from the kernel's space. */
        check("none of it is mapped in the kernel's space",
              paging64_translate(UCODE_VA, &got) == PAGING64_NOT_MAPPED);

        vmspace64_switch(&proc);
        enter_user_mode64(UCODE_VA, USTACK_VA + PAGE64_SIZE, 0);
        vmspace64_switch(&kspace);

        check("it ran and exited", syscall64_count() == calls_before + 2);
        check("it ran at ring 3", syscall64_last_arg() == 0x23);
        check("and the syscall found the kernel from inside its space",
              syscall64_exit_code() == 0x23 + 0x1111);

        vmspace64_destroy(&proc);
        pmm64_free_frame(code_frame);
        pmm64_free_frame(stack_frame);
    }

    /* --- layer 13: two tasks, preempted by the timer ---------------- */
    /* The first thing in this tree to be interrupted while at CPL 3, and
     * therefore the first use of the TSS's rsp0. Everything below rests
     * on one property of the interrupt path: by the time a handler runs,
     * the whole user-visible state of the interrupted task is already a
     * registers64_t in memory, so switching tasks is copying structs. */
    serial64_puts("NOVARIS64: -- preemption --\n");
    {
        const uint64_t UCODE_VA  = 0x0000700000000000ULL;
        const uint64_t USTACK_VA = 0x0000700000010000ULL;
        const uint64_t UDATA_VA  = 0x0000700000020000ULL;
        vmspace64_t kspace, space[2];
        uint64_t data_frame[2];
        uint64_t code_len, exit_off, counters[2];
        int i, ok = 1;

        vmspace64_kernel_space(&kspace);
        code_len = (uint64_t)(task_count_code_end - task_count_code);
        exit_off = (uint64_t)(task_count_exit - task_count_code);
        check("the counting program fits in a page", code_len < PAGE64_SIZE);

        sched64_init();

        for (i = 0; i < 2; i++) {
            uint64_t code_frame, stack_frame;

            if (!vmspace64_create(&space[i])) { ok = 0; break; }
            code_frame    = pmm64_alloc_frame();
            stack_frame   = pmm64_alloc_frame();
            data_frame[i] = pmm64_alloc_frame();
            if (!code_frame || !stack_frame || !data_frame[i]) { ok = 0; break; }

            kmemcpy((void*)(0xFFFFFFFF80000000ULL + code_frame),
                    task_count_code, code_len);
            /* The counter starts at zero, and the kernel reads it back
             * through this same window once the run is over. */
            *(volatile uint64_t*)(0xFFFFFFFF80000000ULL + data_frame[i]) = 0;

            vmspace64_map(&space[i], UCODE_VA, code_frame,
                          PAGE64_PRESENT | PAGE64_USER);
            vmspace64_map(&space[i], USTACK_VA, stack_frame,
                          PAGE64_PRESENT | PAGE64_WRITE | PAGE64_USER);
            vmspace64_map(&space[i], UDATA_VA, data_frame[i],
                          PAGE64_PRESENT | PAGE64_WRITE | PAGE64_USER);

            /* Identical entry point, stack and counter address in both -
             * the two tasks differ only in which address space they run
             * in, which is what makes the counters below mean something. */
            sched64_add(UCODE_VA, USTACK_VA + PAGE64_SIZE, UDATA_VA,
                        &space[i]);
        }
        check("two tasks, each in its own address space", ok);

        if (ok) {
            sched64_set_current(0);
            /* Ends the run after a known number of *ticks*. Counting
             * iterations inside the task instead would make the test
             * depend on how fast the emulator happens to be. */
            sched64_stop_after(8, UCODE_VA + exit_off);

            register_interrupt_handler64(32, sched_timer_handler);
            idt64_irq_set_mask(0, 0);

            vmspace64_switch(&space[0]);
            enter_user_mode64(UCODE_VA, USTACK_VA + PAGE64_SIZE, UDATA_VA);
            /* Returned because one of the two made an exit call. The
             * syscall path cleared IF on the way in and never restored
             * it, so no tick can land between here and the mask below. */
            vmspace64_switch(&kspace);
            idt64_irq_set_mask(0, 1);

            for (i = 0; i < 2; i++)
                counters[i] = *(volatile uint64_t*)
                    (0xFFFFFFFF80000000ULL + data_frame[i]);

            check("the timer switched between them",
                  sched64_switches() >= 8);
            /* Both counters non-zero is the result. One task running
             * would leave the other at exactly zero, and each counter
             * lives in a frame only its own space can reach. */
            check("the first task ran", counters[0] > 0);
            check("the second task ran too", counters[1] > 0);
            check("they counted into different physical frames",
                  data_frame[0] != data_frame[1]);
            check("the task that exited reported its own count",
                  syscall64_exit_code() == counters[0] ||
                  syscall64_exit_code() == counters[1]);

            /* Leave no live tasks behind. Since Milestone 56 exit(2)
             * hands the CPU to a surviving sibling rather than ending
             * the run, so a stale task here would capture the *next*
             * layer's exit and never give control back. */
            sched64_init();

            serial64_puts("NOVARIS64: switches= ");
            serial64_putdec(sched64_switches());
            serial64_puts(", task0 = ");
            serial64_putdec(counters[0]);
            serial64_puts(", task1 = ");
            serial64_putdec(counters[1]);
            serial64_putc('\n');
        }
    }

    /* --- layer 14: a real Linux x86-64 executable ------------------- */
    /* The first thing here that was not written for Novaris. It is an
     * ordinary static ELF64, built by the host toolchain, using Linux's
     * x86-64 syscall numbers and register convention - so if it prints,
     * what this kernel implements is Linux's ABI rather than a private
     * convention shaped like it. That property is the whole reason the
     * 32-bit tree can run real glibc and real Wine. */
    serial64_puts("NOVARIS64: -- a real Linux binary --\n");
    {
        /* Slot 255: the top of the low half, well clear of wherever ld
         * decided to put the program. */
        const uint64_t USTACK_VA = 0x00007FFFFFFFE000ULL;
        vmspace64_t kspace, space;
        elf64_info_t info;
        uint64_t entry, stack_frame;
        uint64_t written_before = syscall64_bytes_written();
        int rc;

        vmspace64_kernel_space(&kspace);
        check("a space for the program", vmspace64_create(&space) != 0);

        rc = elf64_load(hello64_elf, hello64_elf_len, &space, &info);
        entry = info.entry;
        check("the ELF64 loaded", rc == ELF64_OK);
        check("it has an entry point", entry != 0);
        check("and something was mapped for it", elf64_pages_mapped() >= 1);

        /* Milestone 66, asked of the ordinary path rather than of a
         * test written to reach high memory: this program's own text was
         * loaded into a frame the kernel could not have touched before
         * the direct map existed. On a machine with under 1GB there is
         * no such frame and the question does not arise. */
        if (pmm64_highest_addr() > 0x40000000ULL) {
            uint64_t code_phys = 0;
            vmspace64_switch(&space);
            rc = paging64_translate(entry, &code_phys);
            vmspace64_switch(&kspace);
            check("the program's code is mapped", rc == PAGING64_OK);
            check("and it lives above the old 1GB ceiling",
                  code_phys >= 0x40000000ULL);
            serial64_puts("NOVARIS64: code at = ");
            serial64_puthex(code_phys);
            serial64_putc('\n');
        }

        stack_frame = pmm64_alloc_frame();
        check("a stack for it", stack_frame != 0);
        check("its stack mapped",
              vmspace64_map(&space, USTACK_VA, stack_frame,
                            PAGE64_PRESENT | PAGE64_WRITE | PAGE64_USER)
              == PAGING64_OK);

        serial64_puts("NOVARIS64: entry   = ");
        serial64_puthex(entry);
        serial64_puts("\nNOVARIS64: --- its output follows ---\n");

        vmspace64_switch(&space);
        enter_user_mode64(entry, USTACK_VA + PAGE64_SIZE, 0);
        vmspace64_switch(&kspace);

        serial64_puts("NOVARIS64: --- end of its output ---\n");

        /* write(2) reached the kernel with a ring-3 pointer that the
         * kernel could read, which it only can because the high half is
         * shared and the syscall never left the caller's space. */
        check("it wrote to stdout",
              syscall64_bytes_written() > written_before);
        /* 42 is the status the program passes to exit(2). Anything else
         * ending the run - a fault, the scheduler - would not produce it. */
        check("and it exited with its own status, 42",
              syscall64_exit_code() == 42);

        serial64_puts("NOVARIS64: wrote   = ");
        serial64_putdec(syscall64_bytes_written() - written_before);
        serial64_puts(" bytes, exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 15: real glibc ---------------------------------------- */
    /* hello64.s issues three syscalls by hand. This one is an ordinary C
     * program compiled by the host against real glibc, so before main
     * runs it sets up thread-local storage, reads its own program
     * headers out of the auxiliary vector, initialises malloc and builds
     * a buffered stdio stream. Every one of those is a demand on this
     * kernel's ABI, and glibc was compiled long before Novaris existed,
     * so none of them are negotiable. */
    serial64_puts("NOVARIS64: -- real glibc --\n");
    {
        /* 64KB of stack: glibc's startup uses far more of it than a
         * hand-written program does. */
        const uint64_t STACK_PAGES = 16;
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        vmspace64_t kspace, space;
        elf64_info_t info;
        uint64_t rsp, i;
        uint64_t written_before = syscall64_bytes_written();
        uint64_t enosys_before  = syscall64_unimplemented_count();
        int rc, stack_ok = 1;
        static const char* const glibc_argv[] = { "/hello_glibc64", 0 };

        vmspace64_kernel_space(&kspace);
        check("a space for glibc", vmspace64_create(&space) != 0);

        rc = elf64_load(glibc64_elf, glibc64_elf_len, &space, &info);
        check("the glibc binary loaded", rc == ELF64_OK);
        check("it reported where its program headers went",
              info.phdr_va != 0);
        check("and where its heap should start", info.brk_start != 0);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);

        uspace64_reset(&space, info.brk_start);
        rsp = uspace64_build_stack(&space, STACK_TOP, STACK_PAGES,
                                   glibc_argv, &info, 0, 0);
        check("argc/argv/envp/auxv built on it", rsp != 0);
        check("and the stack pointer is 16-byte aligned", (rsp % 16) == 0);

        serial64_puts("NOVARIS64: entry   = ");
        serial64_puthex(info.entry);
        serial64_puts("\nNOVARIS64: phdr    = ");
        serial64_puthex(info.phdr_va);
        serial64_puts(" x");
        serial64_putdec(info.phnum);
        serial64_puts("\nNOVARIS64: brk     = ");
        serial64_puthex(info.brk_start);
        serial64_puts("\nNOVARIS64: --- its output follows ---\n");

        /* Tracing stays off: it prints a line per call, which would bury
         * the program's own output in the transcript the differential
         * compares. syscall64_set_trace(1) is how the startup sequence
         * was worked out in the first place, there being no strace. */
        pf_diagnose = 1;
        vmspace64_switch(&space);
        enter_user_mode64(info.entry, rsp, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;

        serial64_puts("NOVARIS64: --- end of its output ---\n");

        check("glibc reached main and printed",
              syscall64_bytes_written() > written_before);
        check("and the program returned its own status, 7",
              syscall64_exit_code() == 7);

        serial64_puts("NOVARIS64: wrote   = ");
        serial64_putdec(syscall64_bytes_written() - written_before);
        serial64_puts(" bytes, exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_puts(", pages ");
        serial64_putdec(uspace64_pages_allocated());
        serial64_puts(", enosys ");
        serial64_putdec(syscall64_unimplemented_count() - enosys_before);
        serial64_putc('\n');
    }

    /* --- layer 16: a 64-bit Windows executable ---------------------- */
    /* The format chrome.exe is in. Built by mingw, importing from
     * kernel32, linked at a Windows image base, and never told what it
     * would run on - the same relationship the glibc binary above has
     * with Linux. */
    serial64_puts("NOVARIS64: -- a 64-bit Windows PE --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 8;
        vmspace64_t kspace, space;
        pe64_info_t info;
        uint64_t rsp, i;
        uint64_t written_before = win32_64_bytes_written();
        int rc, stack_ok = 1;

        vmspace64_kernel_space(&kspace);
        check("a space for the PE", vmspace64_create(&space) != 0);

        rc = pe64_load(pe64_exe, pe64_exe_len, &space, &info);
        check("the PE32+ loaded", rc == PE64_OK);
        /* mingw links at 0x140000000, the default for a 64-bit image,
         * and this one carries no relocations - so it has to go exactly
         * there or its absolute addresses are wrong. */
        check("at the image base it asked for",
              info.image_base == 0x140000000ULL);
        check("its entry point is inside the image",
              info.entry > info.image_base &&
              info.entry < info.image_base + info.image_size);
        check("all three kernel32 imports were bound", info.imports == 3);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);

        /* Entered as though it had been called: the Windows ABI expects
         * rsp to be 8 past a 16-byte boundary at a function's first
         * instruction, because a return address is sitting there. Get
         * this wrong and the first `movaps` in the program faults on an
         * alignment it was entitled to assume. */
        rsp = STACK_TOP - 8;
        check("the stack pointer is where a call would leave it",
              (rsp % 16) == 8);

        serial64_puts("NOVARIS64: base    = ");
        serial64_puthex(info.image_base);
        serial64_puts("\nNOVARIS64: entry   = ");
        serial64_puthex(info.entry);
        serial64_puts("\nNOVARIS64: imports = ");
        serial64_putdec(info.imports);
        serial64_puts(", relocs ");
        serial64_putdec(info.relocs);
        serial64_puts(", pages ");
        serial64_putdec(info.pages);
        serial64_puts("\nNOVARIS64: --- its output follows ---\n");

        pf_diagnose = 1;
        vmspace64_switch(&space);
        enter_user_mode64(info.entry, rsp, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;

        serial64_puts("NOVARIS64: --- end of its output ---\n");

        /* Reaching WriteFile at all means the import thunk shuffled the
         * Windows argument registers into the kernel's and came back. */
        check("it wrote through WriteFile",
              win32_64_bytes_written() > written_before);
        check("and ExitProcess ended it with its own status, 3",
              syscall64_exit_code() == 3);

        serial64_puts("NOVARIS64: wrote   = ");
        serial64_putdec(win32_64_bytes_written() - written_before);
        serial64_puts(" bytes, exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 17: a PE that ships its own DLL ---------------------- */
    /* chrome.exe's shape: a small executable whose real work is in a
     * library beside it. Two things get proved here that layer 16 could
     * not - resolving an import against a real export table, and moving
     * an image away from the base it was linked at. */
    serial64_puts("NOVARIS64: -- a PE with its own DLL --\n");
    {
        /* Forced, not incidental. Loading the DLL where it asked would
         * leave the relocation code untested, and the first image that
         * genuinely needs it will be chrome.exe. */
        const uint64_t DLL_BIAS    = 0x10000000ULL;
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 8;
        vmspace64_t kspace, space;
        pe64_info_t dll, exe;
        uint64_t rsp, i;
        uint64_t written_before = win32_64_bytes_written();
        int rc_dll, rc_exe, stack_ok = 1;

        vmspace64_kernel_space(&kspace);
        pe64_reset_modules();
        check("a space for the pair", vmspace64_create(&space) != 0);

        rc_dll = pe64_load_dll(dlllib64_dll, dlllib64_dll_len, &space,
                               "dlllib64.dll", DLL_BIAS, &dll);
        check("the DLL loaded", rc_dll == PE64_OK);
        check("it was moved off its preferred base", dll.relocs > 0);
        check("and it is registered as a module", pe64_module_count() == 1);
        /* The DLL imports from kernel32 itself, so it needed thunks of
         * its own before anything could call into it. */
        check("its own kernel32 imports were bound", dll.imports >= 2);

        rc_exe = pe64_load(dlluser64_exe, dlluser64_exe_len, &space, &exe);
        check("the executable loaded", rc_exe == PE64_OK);
        /* Two from the DLL, three from kernel32. The DLL's two resolve
         * to addresses inside it; kernel32's three become thunks. */
        check("all five of its imports were bound", exe.imports == 5);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        rsp = STACK_TOP - 8;

        serial64_puts("NOVARIS64: dll     = ");
        serial64_puthex(dll.image_base);
        serial64_puts(", relocs ");
        serial64_putdec(dll.relocs);
        serial64_puts("\nNOVARIS64: exe     = ");
        serial64_puthex(exe.image_base);
        serial64_puts("\nNOVARIS64: --- its output follows ---\n");

        pf_diagnose = 1;
        vmspace64_switch(&space);
        enter_user_mode64(exe.entry, rsp, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;

        serial64_puts("NOVARIS64: --- end of its output ---\n");

        check("the DLL's code ran",
              win32_64_bytes_written() > written_before);
        /* The executable exits 5 only if the DLL returned exactly 1234.
         * 99 would mean the call arrived but the convention is wrong,
         * which is a different bug from the call not arriving at all. */
        check("and returned the right value across the call",
              syscall64_exit_code() == 5);

        serial64_puts("NOVARIS64: exit    = ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 18: a DLL loaded from a file, by name, at run time ---- */
    /* Everything before this had its libraries resolved before it
     * started, from bytes compiled into the kernel. This program names a
     * file, gets back a module, and finds a function in it - which is
     * what LoadLibrary is, and the shape chrome.exe depends on:
     * chrome_elf.dll *loads* chrome.dll rather than importing it. */
    serial64_puts("NOVARIS64: -- LoadLibrary from a file --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 8;
        vmspace64_t kspace, space;
        pe64_info_t exe;
        uint64_t rsp, i;
        uint64_t loads_before = win32_64_loads();
        int rc, stack_ok = 1;

        check("the initrd was found and parsed",
              initrd64_file_count() > 0);
        {
            const void* probe;
            uint64_t plen = 0;
            check("and dlllib64.dll is in it",
                  initrd64_open("dlllib64.dll", &probe, &plen)
                  == INITRD64_OK && plen > 0);
        }

        vmspace64_kernel_space(&kspace);
        pe64_reset_modules();
        check("a space for the program", vmspace64_create(&space) != 0);

        rc = pe64_load(loader64_exe, loader64_exe_len, &space, &exe);
        check("the program loaded", rc == PE64_OK);
        /* Its import table names kernel32 only - GetStdHandle, WriteFile,
         * LoadLibraryA, GetProcAddress, ExitProcess. The DLL it uses is
         * not in there at all. */
        check("it imports no DLL of its own", pe64_module_count() == 0);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        rsp = STACK_TOP - 8;

        serial64_puts("NOVARIS64: initrd  = ");
        serial64_putdec(initrd64_file_count());
        serial64_puts(" file(s), ");
        serial64_putdec(initrd64_size());
        serial64_puts(" bytes\nNOVARIS64: --- its output follows ---\n");

        pf_diagnose = 1;
        vmspace64_switch(&space);
        enter_user_mode64(exe.entry, rsp, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;

        serial64_puts("NOVARIS64: --- end of its output ---\n");

        /* The exit codes are the program's own diagnosis: 11 is success,
         * and each failure path has its own number so a break says which
         * step broke rather than only that something did. */
        check("LoadLibraryA, GetProcAddress and the call all worked",
              syscall64_exit_code() == 11);
        check("exactly one module was mapped",
              win32_64_loads() == loads_before + 1);
        check("and it is registered under the name it was asked for",
              pe64_module_base("dlllib64.dll") != 0);

        serial64_puts("NOVARIS64: exit    = ");
        serial64_putdec(syscall64_exit_code());
        serial64_puts(", modules loaded ");
        serial64_putdec(win32_64_loads() - loads_before);
        serial64_putc('\n');
    }

    /* --- layer 19: a thread, made with clone(2) --------------------- */
    /* The first thing Wine needs that this tree did not have. Two
     * threads in ONE address space, which is what makes it different
     * from Milestone 49's two tasks: those had a space each and could
     * not have shared a variable if they wanted to. */
    serial64_puts("NOVARIS64: -- threads --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 16;
        vmspace64_t kspace, space;
        elf64_info_t info;
        uint64_t i;
        uint64_t written_before = syscall64_bytes_written();
        /* Earlier layers call exit(2) too, so this counts the delta
         * rather than the total. */
        uint64_t exits_before = syscall64_thread_exits();
        int rc, stack_ok = 1, main_tid;
        registers64_t placeholder;

        vmspace64_kernel_space(&kspace);
        check("a space for it", vmspace64_create(&space) != 0);

        rc = elf64_load(thread64_elf, thread64_elf_len, &space, &info);
        check("the threaded program loaded", rc == ELF64_OK);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        uspace64_reset(&space, info.brk_start);

        /* The main thread has to be a scheduler task before it clones,
         * or there is nothing for the child to be a sibling of. Its
         * frame is a placeholder: the first timer tick overwrites it
         * with the real one before any switch happens. */
        sched64_init();
        for (i = 0; i < sizeof(placeholder) / 8; i++)
            ((uint64_t*)&placeholder)[i] = 0;
        main_tid = sched64_add_frame(&placeholder, &space, 0);
        check("the main thread is a scheduler task", main_tid == 0);
        sched64_set_current(main_tid);

        register_interrupt_handler64(32, sched_timer_handler);
        idt64_irq_set_mask(0, 0);

        serial64_puts("NOVARIS64: --- its output follows ---\n");
        pf_diagnose = 1;
        vmspace64_switch(&space);
        /* The parent spins on a variable only the child writes, so this
         * returns only if the scheduler really ran both. */
        enter_user_mode64(info.entry, STACK_TOP, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;
        idt64_irq_set_mask(0, 1);
        serial64_puts("NOVARIS64: --- end of its output ---\n");

        /* Only the switch count: since Milestone 64 the last process to
         * exit clears the current task, so asserting on that would be
         * testing teardown rather than clone. */
        check("clone created a second thread", sched64_switches() > 0);
        check("both threads ran, sharing one address space",
              syscall64_bytes_written() > written_before);
        /* 23 is the parent's own status. 81 or 82 would mean mmap or
         * clone failed; a hang would mean the child never got the CPU. */
        check("the parent saw the child's write and exited cleanly",
              syscall64_exit_code() == 23);
        /* The child called exit(2), which ends a thread. If that were
         * still a synonym for exit_group(2) the run would have ended
         * with the child's status and the parent would never have
         * printed - which is exactly how Linux caught this. */
        check("the child ended as a thread, not as the process",
              syscall64_thread_exits() == exits_before + 1);

        serial64_puts("NOVARIS64: switches= ");
        serial64_putdec(sched64_switches());
        serial64_puts(", exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 20: a futex ------------------------------------------ */
    /* thread64.s spun. This one sleeps, which is the difference that
     * matters: a kernel implementing FUTEX_WAIT as "return 0" would
     * still pass that test - the parent would loop again - and cannot
     * pass this one, because there is no loop to fall back into. */
    serial64_puts("NOVARIS64: -- futex --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 16;
        vmspace64_t kspace, space;
        elf64_info_t info;
        uint64_t i;
        uint64_t written_before = syscall64_bytes_written();
        uint64_t waits_before   = syscall64_futex_waits();
        uint64_t wakes_before   = syscall64_futex_wakes();
        int rc, stack_ok = 1, main_tid;
        registers64_t placeholder;

        vmspace64_kernel_space(&kspace);
        check("a space for it", vmspace64_create(&space) != 0);

        rc = elf64_load(futex64_elf, futex64_elf_len, &space, &info);
        check("the futex program loaded", rc == ELF64_OK);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        uspace64_reset(&space, info.brk_start);

        sched64_init();
        for (i = 0; i < sizeof(placeholder) / 8; i++)
            ((uint64_t*)&placeholder)[i] = 0;
        main_tid = sched64_add_frame(&placeholder, &space, 0);
        sched64_set_current(main_tid);

        register_interrupt_handler64(32, sched_timer_handler);
        idt64_irq_set_mask(0, 0);

        serial64_puts("NOVARIS64: --- its output follows ---\n");
        pf_diagnose = 1;
        vmspace64_switch(&space);
        enter_user_mode64(info.entry, STACK_TOP, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;
        idt64_irq_set_mask(0, 1);
        sched64_init();
        serial64_puts("NOVARIS64: --- end of its output ---\n");

        check("the handoff happened",
              syscall64_bytes_written() > written_before);
        check("and the program exited with its own status, 31",
              syscall64_exit_code() == 31);
        /* Without these two the run proves nothing: a parent that never
         * contended would take the fast path, never sleep, and pass
         * every assertion above. */
        check("a thread really blocked in futex(2)",
              syscall64_futex_waits() > waits_before);
        check("and a wakeup really woke one",
              syscall64_futex_wakes() > wakes_before);

        serial64_puts("NOVARIS64: waits   = ");
        serial64_putdec(syscall64_futex_waits() - waits_before);
        serial64_puts(", wakes ");
        serial64_putdec(syscall64_futex_wakes() - wakes_before);
        serial64_puts(", exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 21: a signal handler that resumes elsewhere ---------- */
    /* Wine's exception dispatch in miniature: take SIGSEGV, read the
     * saved registers out of the ucontext, write RIP back, carry on.
     * Every layer before this treated a ring-3 fault as the end of the
     * program. */
    serial64_puts("NOVARIS64: -- signals --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 16;
        vmspace64_t kspace, space;
        elf64_info_t info;
        uint64_t i;
        uint64_t written_before = syscall64_bytes_written();
        int rc, stack_ok = 1;

        vmspace64_kernel_space(&kspace);
        signal64_reset();
        check("a space for it", vmspace64_create(&space) != 0);

        rc = elf64_load(signal64_elf, signal64_elf_len, &space, &info);
        check("the signal program loaded", rc == ELF64_OK);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        uspace64_reset(&space, info.brk_start);

        /* pf_diagnose stays OFF: this program is *supposed* to fault,
         * and the diagnostic path halts the machine. */
        serial64_puts("NOVARIS64: --- its output follows ---\n");
        vmspace64_switch(&space);
        enter_user_mode64(info.entry, STACK_TOP, 0);
        vmspace64_switch(&kspace);
        serial64_puts("NOVARIS64: --- end of its output ---\n");

        check("the fault reached a ring-3 handler",
              signal64_delivered() == 1);
        check("and the handler returned through rt_sigreturn",
              signal64_returns() == 1);
        check("the program resumed and printed",
              syscall64_bytes_written() > written_before);
        /* 41 is only reachable through the resume path: the faulting
         * instruction is followed by nothing else that leads there. */
        check("it exited with the status that means it recovered",
              syscall64_exit_code() == 41);

        serial64_puts("NOVARIS64: signals = ");
        serial64_putdec(signal64_delivered());
        serial64_puts(" delivered, ");
        serial64_putdec(signal64_returns());
        serial64_puts(" returned, exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 22: a writable filesystem ---------------------------- */
    /* Milestone 54's initrd could be read. This one can be written to,
     * which is the difference that matters: a Wine prefix is thousands
     * of files Wine *creates*. */
    serial64_puts("NOVARIS64: -- a writable filesystem --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 16;
        vmspace64_t kspace, space;
        elf64_info_t info;
        uint64_t i;
        uint64_t written_before = syscall64_bytes_written();
        int rc, stack_ok = 1;

        ramfs64_init();
        ramfs64_seed_from_initrd();
        syscall64_reset_files();

        check("the filesystem came up with /tmp", ramfs64_lookup("/tmp") >= 0);
        /* Whatever the initrd held is still readable, so this milestone
         * adds writing rather than replacing reading. */
        check("and the initrd's contents were carried into it",
              ramfs64_lookup("/dlllib64.dll") >= 0);

        vmspace64_kernel_space(&kspace);
        check("a space for it", vmspace64_create(&space) != 0);

        rc = elf64_load(fs64_elf, fs64_elf_len, &space, &info);
        check("the filesystem program loaded", rc == ELF64_OK);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        uspace64_reset(&space, info.brk_start);

        serial64_puts("NOVARIS64: --- its output follows ---\n");
        pf_diagnose = 1;
        vmspace64_switch(&space);
        enter_user_mode64(info.entry, STACK_TOP, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;
        serial64_puts("NOVARIS64: --- end of its output ---\n");

        check("the program said so too",
              syscall64_bytes_written() > written_before);
        /* Each failure path in the program has its own status - 71 is a
         * failed open, 75 a mismatched read-back, 77 a file that
         * survived being unlinked - so a break says which step broke. */
        check("open, write, seek, read-back, unlink all worked",
              syscall64_exit_code() == 53);
        check("and the file it removed is gone",
              ramfs64_lookup("/tmp/novaris-fs-test") < 0);

        serial64_puts("NOVARIS64: fs      = ");
        serial64_putdec(ramfs64_count());
        serial64_puts(" nodes, exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 23: a file, mapped ----------------------------------- */
    /* How a loader loads. ld.so maps an ELF's segments and Wine maps a
     * PE's; every image this kernel has run so far was copied in by the
     * kernel rather than mapped by the program. */
    serial64_puts("NOVARIS64: -- file-backed mmap --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 16;
        vmspace64_t kspace, space;
        elf64_info_t info;
        uint64_t i;
        uint64_t written_before = syscall64_bytes_written();
        uint64_t maps_before    = syscall64_file_maps();
        int rc, stack_ok = 1;

        syscall64_reset_files();
        vmspace64_kernel_space(&kspace);
        check("a space for it", vmspace64_create(&space) != 0);

        rc = elf64_load(mmapfile64_elf, mmapfile64_elf_len, &space, &info);
        check("the mmap program loaded", rc == ELF64_OK);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        uspace64_reset(&space, info.brk_start);

        serial64_puts("NOVARIS64: --- its output follows ---\n");
        pf_diagnose = 1;
        vmspace64_switch(&space);
        enter_user_mode64(info.entry, STACK_TOP, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;
        serial64_puts("NOVARIS64: --- end of its output ---\n");

        check("the program reported success",
              syscall64_bytes_written() > written_before);
        /* 94 would mean the mapping held the wrong bytes, 96 that a
         * MAP_PRIVATE write reached the file. 61 is both correct. */
        check("the mapping held the file's bytes, and stayed private",
              syscall64_exit_code() == 61);
        /* Without this the run proves nothing about files: the
         * anonymous path returns a perfectly good pointer. */
        check("and it really was a file-backed mapping",
              syscall64_file_maps() == maps_before + 1);

        serial64_puts("NOVARIS64: maps    = ");
        serial64_putdec(syscall64_file_maps() - maps_before);
        serial64_puts(" file-backed, exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 24: the dynamic loader ------------------------------- */
    /* Wine's loader is a dynamically linked PIE needing
     * /lib64/ld-linux-x86-64.so.2 and libc.so.6, so nothing about Wine
     * can be attempted until ld.so itself runs. This is that experiment
     * at its smallest: load a dynamic program, hand control to its
     * interpreter, and see how far it gets. Tracing is ON - what this
     * layer is for is finding out what ld.so asks for. */
    serial64_puts("NOVARIS64: -- the dynamic loader --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        /* 512KB. ld.so uses far more stack than a hand-written program:
         * it relocates, resolves symbols, and runs initialisers, all
         * recursively. The kernel does not grow a stack on fault the way
         * Linux does, so what it gets at the start is all it gets. */
        const uint64_t STACK_PAGES = 128;
        const uint64_t EXE_BIAS    = 0x0000555555554000ULL;
        const uint64_t INTERP_BASE = 0x00007FFFF7000000ULL;
        vmspace64_t kspace, space;
        elf64_info_t exe, interp;
        const void* image;
        uint64_t len, rsp, i;
        uint64_t written_before = syscall64_bytes_written();
        char interp_path[128];
        int rc, stack_ok = 1, have_interp;
        static const char* const dyn_argv[] = { "/dynhello64", 0 };

        ramfs64_init();
        ramfs64_seed_from_initrd();
        syscall64_reset_files();
        /* Layer 21 installed a SIGSEGV handler and the table outlives
         * its program, so without this a fault here is delivered to a
         * handler belonging to a binary that is no longer loaded - and
         * the frame is written onto this program's stack. Process
         * teardown does this in a real kernel. */
        signal64_reset();
        vmspace64_kernel_space(&kspace);
        check("a space for it", vmspace64_create(&space) != 0);

        check("the dynamic program is in the filesystem",
              initrd64_open("dynhello64", &image, &len) == INITRD64_OK);

        have_interp = elf64_interp(image, len, interp_path,
                                   sizeof(interp_path));
        check("it names a dynamic loader", have_interp == 1);
        serial64_puts("NOVARIS64: interp  = ");
        serial64_puts(have_interp ? interp_path : "(none)");
        serial64_putc('\n');

        /* An ET_DYN executable asks to be placed at 0; the loader
         * chooses. The two biases here are the addresses Linux itself
         * tends to use, which keeps the layout familiar when comparing
         * a trace against a host one. */
        rc = elf64_load_at(image, len, &space, EXE_BIAS, &exe);
        check("the program loaded", rc == ELF64_OK);
        check("and it is position independent", exe.is_dyn == 1);

        {
            const void* ld_image;
            uint64_t ld_len;
            /* The path in PT_INTERP is absolute and the filesystem is
             * flat, so the loader is looked up by its base name. */
            int found = initrd64_open("lib64/ld-linux-x86-64.so.2",
                                      &ld_image, &ld_len) == INITRD64_OK;
            check("the dynamic loader is in the filesystem", found);
            if (found) {
                rc = elf64_load_at(ld_image, ld_len, &space, INTERP_BASE,
                                   &interp);
                check("the dynamic loader loaded", rc == ELF64_OK);
            }
        }

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        uspace64_reset(&space, exe.brk_start);

        /* AT_BASE tells ld.so where it was mapped - it has to relocate
         * its own image before it can relocate anything else - and
         * AT_ENTRY where the program it is loading starts. */
        rsp = uspace64_build_stack(&space, STACK_TOP, STACK_PAGES,
                                   dyn_argv, &exe, INTERP_BASE, 0);
        check("a stack with AT_BASE on it", rsp != 0);

        {
            int libc_node = ramfs64_lookup("/lib/x86_64-linux-gnu/libc.so.6");
            serial64_puts("NOVARIS64: libc    = node ");
            serial64_putdec((uint64_t)(libc_node < 0 ? 0 : libc_node));
            serial64_puts(", ");
            serial64_putdec(ramfs64_size(libc_node));
            serial64_puts(" bytes\n");
        }

        serial64_puts("NOVARIS64: exe     = ");
        serial64_puthex(exe.entry);
        serial64_puts(", ld.so entry ");
        serial64_puthex(interp.entry);
        serial64_puts("\nNOVARIS64: --- what it asks for ---\n");

        /* Control goes to the INTERPRETER, not the program: ld.so runs
         * first and calls the program's entry when it is ready. */
        /* Tracing is off now that this works. It is how the milestone
         * was found - syscall64_set_trace(1) prints every call and its
         * result - and leaving it on would bury the program's own
         * output in the transcript the differential compares. */
        pf_diagnose = 1;
        vmspace64_switch(&space);
        enter_user_mode64(interp.entry, rsp, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;

        serial64_puts("NOVARIS64: --- end ---\n");
        serial64_puts("NOVARIS64: exit    = ");
        serial64_putdec(syscall64_exit_code());
        serial64_puts(", enosys seen ");
        serial64_putdec(syscall64_unimplemented_count());
        serial64_putc('\n');

        /* 67 is what dynhello64.c's main returns, and it is only
         * reachable through the whole chain: ld.so relocated itself,
         * found libc, mapped it, relocated it, resolved
         * __libc_start_main, and called main. */
        check("ld.so loaded libc and reached main",
              syscall64_exit_code() == 67);
        check("the program printed through the libc it linked against",
              syscall64_bytes_written() > written_before);
    }

    /* --- layer 25: Wine's own loader -------------------------------- */
    /* The point of the whole 64-bit port, pointed at the kernel to see
     * what it says. Wine's loader is a dynamically linked PIE, which
     * Milestone 62 made runnable; whether it gets anywhere is a
     * different question, and this layer exists to read the answer
     * rather than to assert one. Tracing is ON. */
    serial64_puts("NOVARIS64: -- Wine's loader --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 128;
        const uint64_t EXE_BIAS    = 0x0000555555554000ULL;
        const uint64_t INTERP_BASE = 0x00007FFFF7000000ULL;
        vmspace64_t kspace, space;
        elf64_info_t exe, interp;
        const void* image;
        const void* ld_image;
        uint64_t len, ld_len, rsp, i;
        uint64_t enosys_before = syscall64_unimplemented_count();
        int rc, stack_ok = 1, have_wine;

        /* Wine derives its prefix from HOME, and glibc derives HOME from
         * the passwd database when the variable is absent - which is a
         * long way to travel for a value that can simply be handed
         * over. WINEDLLPATH is where it looks for the rest of its
         * libraries once ntdll is up. */
        /* Ask it for its version. With no arguments it prints usage,
         * which proves it started; --version makes it go further and
         * answer from ntdll. */
        static const char* const wine_argv[] = { "/wine", "--version", 0 };

        static const char* const wine_env[] = {
            "HOME=/root",
            "USER=root",
            "WINEPREFIX=/root/.wine",
            "WINEDLLPATH=/",
            "WINEDEBUG=+loaddll",
            0
        };

        ramfs64_init();
        ramfs64_seed_from_initrd();
        syscall64_reset_files();
        signal64_reset();
        sched64_init();
        vmspace64_kernel_space(&kspace);

        have_wine = initrd64_open("wine", &image, &len) == INITRD64_OK;
        if (!have_wine) {
            /* Not a failure: the build does not require anyone to have
             * spent an hour compiling Wine first. */
            serial64_puts("NOVARIS64: no Wine loader in the initrd - "
                          "build one with configure --enable-archs=x86_64\n");
        } else if (vmspace64_create(&space) &&
                   initrd64_open("lib64/ld-linux-x86-64.so.2",
                                 &ld_image, &ld_len) == INITRD64_OK) {

            serial64_puts("NOVARIS64: wine    = ");
            serial64_putdec(len);
            serial64_puts(" bytes\n");

            /* Wine reads /proc/self/exe to work out where it is
             * installed, and derives the path to ntdll.so from it. */
            syscall64_set_exe_path("/wine");

            rc = elf64_load_at(image, len, &space, EXE_BIAS, &exe);
            if (rc == ELF64_OK)
                rc = elf64_load_at(ld_image, ld_len, &space, INTERP_BASE,
                                   &interp);

            for (i = 0; i < STACK_PAGES; i++) {
                uint64_t f = pmm64_alloc_frame();
                if (!f || vmspace64_map(&space,
                                        STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                        PAGE64_PRESENT | PAGE64_WRITE |
                                        PAGE64_USER) != PAGING64_OK)
                    stack_ok = 0;
            }
            uspace64_reset(&space, exe.brk_start);
            rsp = uspace64_build_stack(&space, STACK_TOP, STACK_PAGES,
                                       wine_argv, &exe, INTERP_BASE,
                                       wine_env);

            if (rc == ELF64_OK && stack_ok && rsp) {
                serial64_puts("NOVARIS64: --- what Wine asks for ---\n");
                pf_diagnose = 1;
                syscall64_set_trace(1);
                vmspace64_switch(&space);
                enter_user_mode64(interp.entry, rsp, 0);
                vmspace64_switch(&kspace);
                syscall64_set_trace(0);
                pf_diagnose = 0;
                serial64_puts("NOVARIS64: --- end ---\n");
            } else {
                serial64_puts("NOVARIS64: could not lay it out\n");
            }
        }

        serial64_puts("NOVARIS64: wine exit= ");
        serial64_putdec(syscall64_exit_code());
        serial64_puts(", enosys ");
        serial64_putdec(syscall64_unimplemented_count() - enosys_before);
        serial64_puts(", last ");
        serial64_putdec(syscall64_unimplemented());
        serial64_putc('\n');

        /* Asserted only when a Wine was actually built to run: the
         * repository must not require an hour of compiling Wine before
         * `make test` passes. When it is there, `wine --version` exits
         * 0 and nothing else in this kernel produces that. */
        if (have_wine)
            check("Wine's loader ran and answered --version",
                  syscall64_exit_code() == 0);
        else
            check("no Wine to run, which is not a failure", 1);
    }

    /* --- layer 26: fork, execve, wait ------------------------------- */
    /* The shape every shell has, and the one Wine's architecture is
     * built on: a process copies itself, the copy becomes a different
     * program, and the original waits to be told how it went. */
    serial64_puts("NOVARIS64: -- fork and execve --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 32;
        vmspace64_t kspace;
        elf64_info_t info;
        uint64_t i, rsp;
        uint64_t written_before = syscall64_bytes_written();
        uint64_t forks_before   = syscall64_forks();
        uint64_t execs_before   = syscall64_execs();
        int rc, stack_ok = 1, pid;
        proc64_t* p;
        static const char* const fe_argv[] = { "/forkexec64", 0 };

        ramfs64_init();
        ramfs64_seed_from_initrd();
        signal64_reset();
        sched64_init();
        proc64_init();
        vmspace64_kernel_space(&kspace);

        check("the child program is in the filesystem",
              ramfs64_lookup("/tmp/forkchild64") >= 0);

        pid = proc64_create();
        check("a process to start from", pid > 0);
        proc64_set_current(pid);
        p = proc64_current();

        check("a space for it", vmspace64_create(&p->space) != 0);
        rc = elf64_load(forkexec64_elf, forkexec64_elf_len, &p->space, &info);
        check("the forking program loaded", rc == ELF64_OK);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&p->space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        uspace64_reset(&p->space, info.brk_start);
        rsp = uspace64_build_stack(&p->space, STACK_TOP, STACK_PAGES,
                                   fe_argv, &info, 0, 0);

        /* The starting process has to be a scheduler task before it
         * forks, so the child has somewhere to be a sibling of. */
        {
            registers64_t first;
            for (i = 0; i < sizeof(first) / 8; i++)
                ((uint64_t*)&first)[i] = 0;
            sched64_add_frame_for(&first, &p->space, 0, pid);
            sched64_set_current(0);
        }

        register_interrupt_handler64(32, sched_timer_handler);
        idt64_irq_set_mask(0, 0);

        serial64_puts("NOVARIS64: --- its output follows ---\n");
        pf_diagnose = 1;
        vmspace64_switch(&p->space);
        enter_user_mode64(info.entry, rsp, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;
        idt64_irq_set_mask(0, 1);
        serial64_puts("NOVARIS64: --- end of its output ---\n");

        check("fork made a process", syscall64_forks() == forks_before + 1);
        check("execve replaced one", syscall64_execs() == execs_before + 1);
        check("both programs printed",
              syscall64_bytes_written() > written_before);
        /* 71 is the parent's own status, and it is only reachable if
         * wait4 returned the child's pid AND the status carried the 24
         * the execed program exited with. 96/97/98 would each name a
         * different step. */
        check("the parent waited and got the child's status back",
              syscall64_exit_code() == 71);

        serial64_puts("NOVARIS64: procs   = ");
        serial64_putdec(proc64_count());
        serial64_puts(" left, exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 27: a real directory tree ---------------------------- */
    /* Everything a flat path table could not do: nested mkdir where the
     * inner needs the outer, open through "..", getdents64 over actual
     * children, and rmdir refusing a directory that still holds
     * something. A Wine prefix is a deep tree Wine walks, so this is
     * the difference between a simplification and a lie. */
    serial64_puts("NOVARIS64: -- a directory tree --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 32;
        vmspace64_t kspace;
        elf64_info_t info;
        uint64_t i, rsp;
        uint64_t written_before = syscall64_bytes_written();
        int rc, stack_ok = 1, pid;
        proc64_t* p;
        static const char* const tree_argv[] = { "/tree64", 0 };

        ramfs64_init();
        ramfs64_seed_from_initrd();
        signal64_reset();
        sched64_init();
        proc64_init();
        vmspace64_kernel_space(&kspace);

        /* The seed had to build directories on the way down, which the
         * flat version never needed to. */
        check("the initrd's nested paths became real directories",
              ramfs64_is_dir(ramfs64_lookup("/lib")) &&
              ramfs64_is_dir(ramfs64_lookup("/lib/x86_64-linux-gnu")));
        check("and the file at the bottom of them is a file",
              ramfs64_lookup("/lib/x86_64-linux-gnu/libc.so.6") >= 0);
        check("\"..\" resolves rather than matching a string",
              ramfs64_lookup("/lib/x86_64-linux-gnu/../../etc/passwd") ==
              ramfs64_lookup("/etc/passwd"));

        pid = proc64_create();
        proc64_set_current(pid);
        p = proc64_current();

        check("a space for it", vmspace64_create(&p->space) != 0);
        rc = elf64_load(tree64_elf, tree64_elf_len, &p->space, &info);
        check("the tree program loaded", rc == ELF64_OK);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&p->space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        uspace64_reset(&p->space, info.brk_start);
        rsp = uspace64_build_stack(&p->space, STACK_TOP, STACK_PAGES,
                                   tree_argv, &info, 0, 0);

        {
            registers64_t first;
            for (i = 0; i < sizeof(first) / 8; i++)
                ((uint64_t*)&first)[i] = 0;
            sched64_add_frame_for(&first, &p->space, 0, pid);
            sched64_set_current(0);
        }

        serial64_puts("NOVARIS64: --- its output follows ---\n");
        pf_diagnose = 1;
        vmspace64_switch(&p->space);
        enter_user_mode64(info.entry, rsp, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;
        serial64_puts("NOVARIS64: --- end of its output ---\n");

        check("the program said so too",
              syscall64_bytes_written() > written_before);
        /* Each step has its own status: 68 would mean getdents64 did not
         * list the subdirectory, 69 that rmdir removed a directory that
         * still had something in it, 63 that ".." did not resolve. */
        check("mkdir, \"..\", getdents64 and rmdir all behaved",
              syscall64_exit_code() == 83);
        check("and it removed everything it made",
              ramfs64_lookup("/tmp/nvtree") < 0);

        serial64_puts("NOVARIS64: nodes   = ");
        serial64_putdec(ramfs64_count());
        serial64_puts(", exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 28: a process draws on the screen (Milestone 67) ----- */
    /* The kernel drawing to its own framebuffer proves the driver. This
     * proves the *interface*: an ordinary Linux fbdev client, built by
     * the host compiler, opening /dev/fb0 and asking the two FBIOGET
     * questions before mapping it and drawing - which is the shape of
     * every display driver that would ever sit above this kernel,
     * Wine's included. */
    serial64_puts("NOVARIS64: -- a process draws --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 32;
        vmspace64_t space, kspace;
        elf64_info_t info;
        uint64_t i, rsp;
        int rc, stack_ok = 1;
        static const char* const fb_argv[] = { "/fbdraw64", 0 };

        ramfs64_init();
        ramfs64_seed_from_initrd();
        proc64_init();
        proc64_set_current(proc64_create());
        vmspace64_kernel_space(&kspace);

        if (!fb64_ready()) {
            serial64_puts("NOVARIS64: SKIP  no framebuffer to draw on\n");
        } else if (fb64_width() < 1024 || fb64_height() < 768) {
            /* The program refuses a screen it cannot address, and says
             * so with a status of its own - so this is still an
             * assertion about behaviour, not a skipped test. */
            serial64_puts("NOVARIS64: SKIP  screen too small for fbdraw\n");
        } else {
            check("the framebuffer registered as /dev/fb0", fb64_register());
            check("and /dev/fb0 is in the filesystem",
                  ramfs64_lookup("/dev/fb0") >= 0);
            check("it is a device, not an ordinary file",
                  ramfs64_device(ramfs64_lookup("/dev/fb0"))
                  == RAMFS64_DEV_FB);

            check("a space for it", vmspace64_create(&space) != 0);
            rc = elf64_load(fbdraw64_elf, fbdraw64_elf_len, &space, &info);
            check("the drawing program loaded", rc == ELF64_OK);

            for (i = 0; i < STACK_PAGES; i++) {
                uint64_t f = pmm64_alloc_frame();
                if (!f || vmspace64_map(&space,
                                        STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                        PAGE64_PRESENT | PAGE64_WRITE |
                                        PAGE64_USER) != PAGING64_OK)
                    stack_ok = 0;
            }
            check("a stack for it", stack_ok);
            uspace64_reset(&space, info.brk_start);
            rsp = uspace64_build_stack(&space, STACK_TOP, STACK_PAGES,
                                       fb_argv, &info, 0, 0);

            /* The band is not on the screen yet, and has to not be:
             * otherwise "the process drew it" and "something else did"
             * are the same observation. */
            check("the screen is untouched where the program will draw",
                  fb64_get_pixel(500, 650) != 0x00FF00FF);

            serial64_puts("NOVARIS64: --- its output follows ---\n");
            pf_diagnose = 1;
            vmspace64_switch(&space);
            enter_user_mode64(info.entry, rsp, 0);
            vmspace64_switch(&kspace);
            pf_diagnose = 0;
            serial64_puts("NOVARIS64: --- end of its output ---\n");

            check("the program drew and verified its own pixels",
                  syscall64_exit_code() == 0);

            /* The strong one. The kernel reads VRAM through its own
             * mapping and finds what a ring-3 process wrote through a
             * completely different one. A private copy - which is what
             * every other file mapping in this kernel is - would leave
             * this pixel unchanged and the program would still have
             * exited 0, because from inside the process the two are
             * indistinguishable. */
            check("and those pixels are in the kernel's view of VRAM",
                  fb64_get_pixel(500, 650) == 0x00FF00FF);
            check("the band has edges where the program put them",
                  fb64_get_pixel(500, 619) != 0x00FF00FF &&
                  fb64_get_pixel(99,  650) != 0x00FF00FF);

            serial64_puts("NOVARIS64: fbdraw  = exit ");
            serial64_putdec(syscall64_exit_code());
            serial64_putc('\n');
        }
    }

    /* --- layer 29: a working directory, and links (Milestone 68) ---- */
    /* The last two things standing between this kernel and a Wine
     * prefix, and both were absences rather than bugs: every relative
     * path was answered -ENOENT because there was no directory to
     * measure one against, and there were no symlinks at all - which is
     * how a prefix reaches drive C.
     *
     * userland/cwd64.c is an ordinary C program against real glibc, so
     * glibc picks the calls (openat with AT_FDCWD, unlinkat with
     * AT_REMOVEDIR, newfstatat) and this kernel answers whichever it
     * picks. The host runs the same file, and the two outputs are
     * compared byte for byte. */
    serial64_puts("NOVARIS64: -- a working directory --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 32;
        vmspace64_t kspace;
        elf64_info_t info;
        uint64_t i, rsp;
        int rc, stack_ok = 1, pid;
        proc64_t* p;
        static const char* const cwd_argv[] = { "/cwd64", 0 };

        ramfs64_init();
        ramfs64_seed_from_initrd();
        signal64_reset();
        sched64_init();
        proc64_init();
        vmspace64_kernel_space(&kspace);

        /* Three the kernel can settle before the program runs, because
         * a wrong answer here would show up inside it as something
         * else entirely. */
        check("a fresh process starts at the root",
              (pid = proc64_create()) > 0 &&
              kstrcmp(proc64_get(pid)->cwd, "/") == 0);
        {
            int link = ramfs64_symlink("/tmp/etc-link", "../etc");
            check("a symlink can be made", link >= 0);
            check("and it resolves through to its target",
                  ramfs64_lookup("/tmp/etc-link/passwd") ==
                  ramfs64_lookup("/etc/passwd"));
            check("while lookup_nofollow stops at the link itself",
                  ramfs64_lookup_nofollow("/tmp/etc-link") == link);
            ramfs64_unlink("/tmp/etc-link");
        }
        /* A loop must be refused rather than hang the kernel. Nothing
         * below this line would ever run if it did. */
        {
            ramfs64_symlink("/tmp/loop_a", "/tmp/loop_b");
            ramfs64_symlink("/tmp/loop_b", "/tmp/loop_a");
            check("a symlink loop is refused, not followed",
                  ramfs64_lookup("/tmp/loop_a") < 0);
            ramfs64_unlink("/tmp/loop_a");
            ramfs64_unlink("/tmp/loop_b");
        }

        /* The sizing, tested rather than asserted.
         *
         * Raising RAMFS64_MAX_NODES from 192 to 4096 is one line and
         * proves nothing on its own - the old table would have failed
         * on the 193rd node, and nothing above builds 193 of anything.
         * So build a tree the shape of the thing this is for: a prefix
         * measured at 1049 nodes, so 60 directories of 21 files is
         * 1320, comfortably past both the old ceiling and the real
         * requirement.
         *
         * It also exercises the child lists. With the old whole-table
         * scan every one of these creates walked 4096 entries looking
         * for a free slot and every lookup walked it again looking for
         * a sibling; at this size that is the quadratic kmalloc of
         * Milestone 46 in a different file. */
        {
            uint64_t before = ramfs64_count();
            int made = 0, found = 0;
            char path[128];

            for (int d = 0; d < 60; d++) {
                char dir[64];
                uint64_t n = 0;
                kstrlcpy(dir, "/tmp/pfx/d", sizeof(dir));
                n = kstrlen(dir);
                n += ku32_to_dec((uint32_t)d, dir + n);
                dir[n] = 0;
                if (ramfs64_mkdirp(dir) < 0) continue;

                for (int f = 0; f < 21; f++) {
                    uint64_t m;
                    kstrlcpy(path, dir, sizeof(path));
                    m = kstrlen(path);
                    path[m++] = '/';
                    path[m++] = 'f';
                    m += ku32_to_dec((uint32_t)f, path + m);
                    path[m] = 0;
                    if (ramfs64_create(path, 0) >= 0) made++;
                }
            }

            /* Every one of them still findable - which is the claim a
             * child list has to earn, since a broken sibling pointer
             * loses a whole directory silently. */
            for (int d = 0; d < 60; d++) {
                for (int f = 0; f < 21; f++) {
                    uint64_t m;
                    kstrlcpy(path, "/tmp/pfx/d", sizeof(path));
                    m = kstrlen(path);
                    m += ku32_to_dec((uint32_t)d, path + m);
                    path[m++] = '/';
                    path[m++] = 'f';
                    m += ku32_to_dec((uint32_t)f, path + m);
                    path[m] = 0;
                    if (ramfs64_lookup(path) >= 0) found++;
                }
            }

            check("a prefix-sized tree fits (1260 files past the old 192)",
                  made == 1260);
            check("and every file in it is still findable", found == 1260);
            check("the node count agrees with what was made",
                  ramfs64_count() == before + 1260 + 61);

            serial64_puts("NOVARIS64: nodes   = ");
            serial64_putdec(ramfs64_count());
            serial64_puts(" of ");
            serial64_putdec(RAMFS64_MAX_NODES);
            serial64_putc('\n');

            /* Back to a clean filesystem for the program below, which
             * asserts on what it finds. */
            ramfs64_init();
            ramfs64_seed_from_initrd();
        }

        proc64_set_current(pid);
        p = proc64_current();

        check("a space for it", vmspace64_create(&p->space) != 0);
        rc = elf64_load(cwd64_elf, cwd64_elf_len, &p->space, &info);
        check("the cwd program loaded", rc == ELF64_OK);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&p->space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        uspace64_reset(&p->space, info.brk_start);
        rsp = uspace64_build_stack(&p->space, STACK_TOP, STACK_PAGES,
                                   cwd_argv, &info, 0, 0);

        {
            registers64_t first;
            for (i = 0; i < sizeof(first) / 8; i++)
                ((uint64_t*)&first)[i] = 0;
            sched64_add_frame_for(&first, &p->space, 0, pid);
            sched64_set_current(0);
        }

        serial64_puts("NOVARIS64: --- its output follows ---\n");
        pf_diagnose = 1;
        vmspace64_switch(&p->space);
        enter_user_mode64(info.entry, rsp, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;
        serial64_puts("NOVARIS64: --- end of its output ---\n");

        /* 89 means every one of its own assertions passed. 1 means it
         * ran to the end and disagreed with Linux somewhere, which the
         * differential in Makefile.amd64 will name. */
        check("the working directory and symlinks behaved",
              syscall64_exit_code() == 89);
        check("and it left nothing behind",
              ramfs64_lookup("/tmp/novaris_cwd_test") < 0);

        serial64_puts("NOVARIS64: cwd64   = exit ");
        serial64_putdec(syscall64_exit_code());
        serial64_putc('\n');
    }

    /* --- layer 30: fork that shares (Milestone 69) ------------------- */
    /* The program below cannot tell copy-on-write from an eager copy -
     * both produce exactly its output, which is the point: correctness
     * is what it checks. The difference is a cost, and a cost is only
     * visible from here, by counting frames across the fork itself. */
    serial64_puts("NOVARIS64: -- fork that shares --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 64;
        vmspace64_t kspace;
        elf64_info_t info;
        uint64_t i, rsp;
        uint64_t breaks_before = cow_breaks;
        uint64_t dbl_before = pmm64_double_frees();
        int rc, stack_ok = 1, pid;
        proc64_t* p;
        static const char* const cow_argv[] = { "/cowfork64", 0 };

        ramfs64_init();
        ramfs64_seed_from_initrd();
        signal64_reset();
        sched64_init();
        proc64_init();
        vmspace64_kernel_space(&kspace);

        /* The refcount table, before anything shares anything. */
        {
            uint64_t f = pmm64_alloc_frame();
            check("a fresh frame has exactly one owner",
                  pmm64_frame_owners(f) == 1);
            check("sharing it adds an owner",
                  pmm64_ref_frame(f) && pmm64_frame_owners(f) == 2);
            check("freeing it once drops the owner, not the frame",
                  (pmm64_free_frame(f), pmm64_frame_owners(f) == 1));
            pmm64_free_frame(f);
            check("and freeing it again returns it",
                  pmm64_frame_owners(f) == 0);
            check("VRAM is not a frame this allocator owns",
                  !pmm64_owns(fb64_phys()));
        }

        pid = proc64_create();
        proc64_set_current(pid);
        p = proc64_current();

        check("a space for it", vmspace64_create(&p->space) != 0);
        rc = elf64_load(cowfork64_elf, cowfork64_elf_len, &p->space, &info);
        check("the cow program loaded", rc == ELF64_OK);

        for (i = 0; i < STACK_PAGES; i++) {
            uint64_t f = pmm64_alloc_frame();
            if (!f || vmspace64_map(&p->space,
                                    STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                    PAGE64_PRESENT | PAGE64_WRITE |
                                    PAGE64_USER) != PAGING64_OK)
                stack_ok = 0;
        }
        check("a stack for it", stack_ok);
        uspace64_reset(&p->space, info.brk_start);
        rsp = uspace64_build_stack(&p->space, STACK_TOP, STACK_PAGES,
                                   cow_argv, &info, 0, 0);

        {
            registers64_t first;
            for (i = 0; i < sizeof(first) / 8; i++)
                ((uint64_t*)&first)[i] = 0;
            sched64_add_frame_for(&first, &p->space, 0, pid);
            sched64_set_current(0);
        }

        serial64_puts("NOVARIS64: --- its output follows ---\n");
        pf_diagnose = 1;
        vmspace64_switch(&p->space);
        enter_user_mode64(info.entry, rsp, 0);
        vmspace64_switch(&kspace);
        pf_diagnose = 0;
        serial64_puts("NOVARIS64: --- end of its output ---\n");

        /* A frame freed twice is handed out while somebody still holds
         * it, and the next allocation zeroes it - which presents as
         * memory that was correct a moment ago now reading as zeroes,
         * a long way from the free that caused it. */
        serial64_puts("NOVARIS64: dblfree = ");
        serial64_putdec(pmm64_double_frees() - dbl_before);
        serial64_putc('\n');
        check("no frame was freed twice across the fork",
              pmm64_double_frees() == dbl_before);

        check("the parent and the child stayed independent",
              syscall64_exit_code() == 97);

        /* The measurement. The program holds 8MB - 2048 frames - and an
         * eager clone charges every one of them to the fork. Sharing
         * charges only the page tables needed to describe them, which
         * for 8MB is four page tables plus the levels above.
         *
         * 512 is not a tuned number: it is a quarter of what copying
         * costs, so the assertion cannot be satisfied by a fork that
         * copied even a quarter of the buffer. */
        serial64_puts("NOVARIS64: fork    = ");
        serial64_putdec(syscall64_last_fork_frames());
        serial64_puts(" frames for an 8MB process, ");
        serial64_putdec(cow_breaks - breaks_before);
        serial64_puts(" pages copied on write\n");

        check("the fork did not pay for the process it forked",
              syscall64_last_fork_frames() < 512);
        /* And it did share: a fork that had copied eagerly would break
         * nothing later, because nothing would be shared to break. The
         * child writes 8MB, so this is thousands. */
        check("writing to the shared pages copied them one at a time",
              cow_breaks - breaks_before > 1024);
    }

    /* --- layer 31: keyboard and mouse (Milestone 70) ----------------- */
    /* Milestone 67 gave this tree a display and said plainly what was
     * still missing: "no input at all - no keyboard, no mouse. A
     * display without input is half a desktop."
     *
     * The decoding is the small half of this. The interface is the
     * point, and it is the same argument /dev/fb0 made: a driver only
     * the kernel can read is not a driver. So these are device nodes
     * that hand back Linux's own struct input_event, because evdev is
     * what Wine sits on top of on Linux.
     *
     * The scancodes below are fed in rather than typed. Every
     * assertion here is about the decoder, and a decoder tested through
     * an emulated controller is testing QEMU as much as itself -
     * tools/inputtest.py does that part, with real keystrokes from the
     * QEMU monitor, and it is the one that would catch a driver that
     * decoded perfectly and never received anything. */
    serial64_puts("NOVARIS64: -- keyboard and mouse --\n");
    {
        input64_event_t evs[8];
        uint64_t got;

        ramfs64_init();
        ramfs64_seed_from_initrd();
        input64_reset();

        check("the input devices registered", input64_register());
        check("and /dev/input/event0 is a keyboard",
              ramfs64_device(ramfs64_lookup("/dev/input/event0"))
              == RAMFS64_DEV_KBD);
        check("and /dev/input/event1 is a mouse",
              ramfs64_device(ramfs64_lookup("/dev/input/event1"))
              == RAMFS64_DEV_MOUSE);
        check("nothing is queued before anything happens",
              input64_queued(INPUT64_KBD) == 0);

        /* 'A': make 0x1E, break 0x9E. Linux's KEY_A is 30, which is
         * 0x1E - the keycodes for this block *are* the set-1 scancodes,
         * which is why there is no translation table here. */
        input64_feed_scancode(0x1E);
        input64_feed_scancode(0x9E);

        got = input64_read(INPUT64_KBD, evs, sizeof(evs));
        check("a press and a release arrived, each with its SYN",
              got == 4 * sizeof(input64_event_t));
        check("the press is KEY_A down",
              evs[0].type == EV64_KEY && evs[0].code == 30 &&
              evs[0].value == 1);
        check("followed by a SYN_REPORT",
              evs[1].type == EV64_SYN && evs[1].code == SYN64_REPORT);
        check("the release is the same key, up",
              evs[2].type == EV64_KEY && evs[2].code == 30 &&
              evs[2].value == 0);
        check("and the queue is empty again",
              input64_queued(INPUT64_KBD) == 0);

        /* Shift is a key in its own right *and* a modifier. Reporting
         * only the modifier would lose the keystroke; tracking only the
         * keystroke would lose the state. */
        input64_feed_scancode(0x2A);
        check("holding shift sets the modifier",
              input64_modifiers() & INPUT64_MOD_SHIFT);
        input64_feed_scancode(0xAA);
        check("and releasing it clears the modifier",
              !(input64_modifiers() & INPUT64_MOD_SHIFT));
        input64_read(INPUT64_KBD, evs, sizeof(evs));

        /* The mouse. Three bytes: flags, dx, dy. Bit 3 of the flags is
         * always set on a real packet. */
        input64_feed_mouse_byte(0x08);      /* no buttons, no sign bits */
        input64_feed_mouse_byte(5);         /* dx = +5                  */
        input64_feed_mouse_byte(3);         /* dy = +3                  */

        got = input64_read(INPUT64_MOUSE, evs, sizeof(evs));
        check("a move produced X, Y and a SYN",
              got == 3 * sizeof(input64_event_t));
        check("X is the delta as sent",
              evs[0].type == EV64_REL && evs[0].code == REL64_X &&
              evs[0].value == 5);
        /* The mouse counts Y upwards and the screen counts it down. A
         * driver that passed this through unchanged would move the
         * pointer the wrong way, which is the single most obvious bug a
         * mouse driver can have and the easiest to leave in. */
        check("Y is inverted, because a screen counts downwards",
              evs[1].type == EV64_REL && evs[1].code == REL64_Y &&
              evs[1].value == -3);

        /* A negative delta arrives as a positive byte plus a sign bit,
         * not as a two's complement byte the reader can just cast. */
        input64_feed_mouse_byte(0x08 | 0x10);   /* X sign set */
        input64_feed_mouse_byte(0xFB);          /* -5         */
        input64_feed_mouse_byte(0);
        input64_read(INPUT64_MOUSE, evs, sizeof(evs));
        check("a negative delta is sign-extended from nine bits",
              evs[0].type == EV64_REL && evs[0].code == REL64_X &&
              evs[0].value == -5);

        input64_feed_mouse_byte(0x08 | 0x01);   /* left button down */
        input64_feed_mouse_byte(0);
        input64_feed_mouse_byte(0);
        input64_read(INPUT64_MOUSE, evs, sizeof(evs));
        check("a button press is BTN_LEFT down",
              evs[0].type == EV64_KEY && evs[0].code == BTN64_LEFT &&
              evs[0].value == 1);

        /* A first byte without bit 3 is a stream out of phase - an
         * unread ACK is the usual cause. Shifting it in would leave
         * every packet after it wrong; dropping it re-syncs. */
        input64_reset();
        input64_feed_mouse_byte(0xFA);          /* an ACK, not a packet */
        input64_feed_mouse_byte(0x08);
        input64_feed_mouse_byte(7);
        input64_feed_mouse_byte(0);
        got = input64_read(INPUT64_MOUSE, evs, sizeof(evs));
        check("a stray ACK is dropped rather than shifted in",
              got == 2 * sizeof(input64_event_t) &&
              evs[0].code == REL64_X && evs[0].value == 7);

        /* Reads are whole records. */
        input64_reset();
        input64_feed_scancode(0x1E);
        check("a read with room for less than one event returns nothing",
              input64_read(INPUT64_KBD, evs,
                           sizeof(input64_event_t) - 1) == 0);
        check("and the event is still queued afterwards",
              input64_queued(INPUT64_KBD) == 2);

        serial64_puts("NOVARIS64: input   = irq1 ");
        serial64_putdec(input64_irqs(INPUT64_KBD));
        serial64_puts(", irq12 ");
        serial64_putdec(input64_irqs(INPUT64_MOUSE));
        serial64_putc('\n');
    }

    /* --- verdict ---------------------------------------------------- */
    serial64_puts("NOVARIS64: failures = ");
    serial64_putdec((uint64_t)failures);
    serial64_putc('\n');
    /* --- layer 32: a Wine prefix (Milestone 71) ---------------------- */
    /* Milestone 68 removed every reason a prefix could not exist here -
     * the node ceiling, the name and path ceilings, the missing links,
     * the missing working directory - and proved each one separately.
     * It did not run wineboot. This does.
     *
     * It runs only when a whole Wine installation is in the initrd,
     * which is off by default because it is 64MB:
     *
     *     make -f Makefile.amd64 WINE64_INSTALL=1 test-wine-prefix
     *
     * 64MB is not a guess either. Wine builds 602 PE DLLs; creating a
     * prefix was measured to load 93 of them (tools/wine_prefix_modules
     * .txt), which is 174MB in the build tree and 58MB stripped.
     */
    serial64_puts("NOVARIS64: -- a Wine prefix --\n");
    {
        const uint64_t STACK_TOP   = 0x00007FFFFFFF0000ULL;
        const uint64_t STACK_PAGES = 128;
        const uint64_t EXE_BIAS    = 0x0000555555554000ULL;
        const uint64_t INTERP_BASE = 0x00007FFFF7000000ULL;
        vmspace64_t kspace;
        elf64_info_t exe, interp;
        const void* image;
        const void* ld_image;
        uint64_t len, ld_len, rsp, i;
        uint64_t enosys_before = syscall64_unimplemented_count();
        int rc, stack_ok = 1, pid;
        proc64_t* p;

        static const char* const boot_argv[] = {
            "/usr/bin/wine", "wineboot", "-u", 0
        };
        static const char* const boot_env[] = {
            "HOME=/root",
            "USER=root",
            "WINEPREFIX=/root/.wine",
            "WINEDEBUG=-all",
            0
        };

        ramfs64_init();
        ramfs64_seed_from_initrd();
        syscall64_reset_files();
        signal64_reset();
        sched64_init();
        proc64_init();
        vmspace64_kernel_space(&kspace);

        if (ramfs64_lookup("/usr/lib/wine/x86_64-windows/wineboot.exe") < 0) {
            /* Not a failure: the build must not require 64MB of Wine in
             * the initrd before `make test` passes. */
            serial64_puts("NOVARIS64: no Wine installation in the initrd - "
                          "build with WINE64_INSTALL=1\n");
        } else if (initrd64_open("usr/bin/wine", &image, &len) == INITRD64_OK &&
                   initrd64_open("lib64/ld-linux-x86-64.so.2",
                                 &ld_image, &ld_len) == INITRD64_OK) {

            serial64_puts("NOVARIS64: install = ");
            serial64_putdec(ramfs64_count());
            serial64_puts(" nodes\n");

            pid = proc64_create();
            proc64_set_current(pid);
            p = proc64_current();

            check("a space for wineboot", vmspace64_create(&p->space) != 0);

            /* Wine reads /proc/self/exe and derives its library
             * directory from it, so this is not decoration: with the
             * wrong answer it looks for ntdll.so in the wrong place and
             * stops. */
            syscall64_set_exe_path("/usr/bin/wine");

            rc = elf64_load_at(image, len, &p->space, EXE_BIAS, &exe);
            if (rc == ELF64_OK)
                rc = elf64_load_at(ld_image, ld_len, &p->space, INTERP_BASE,
                                   &interp);
            check("the loader and ld.so laid out", rc == ELF64_OK);

            for (i = 0; i < STACK_PAGES; i++) {
                uint64_t f = pmm64_alloc_frame();
                if (!f || vmspace64_map(&p->space,
                                        STACK_TOP - (i + 1) * PAGE64_SIZE, f,
                                        PAGE64_PRESENT | PAGE64_WRITE |
                                        PAGE64_USER) != PAGING64_OK)
                    stack_ok = 0;
            }
            check("a stack for it", stack_ok);
            uspace64_reset(&p->space, exe.brk_start);
            rsp = uspace64_build_stack(&p->space, STACK_TOP, STACK_PAGES,
                                       boot_argv, &exe, INTERP_BASE,
                                       boot_env);

            {
                registers64_t first;
                for (i = 0; i < sizeof(first) / 8; i++)
                    ((uint64_t*)&first)[i] = 0;
                sched64_add_frame_for(&first, &p->space, 0, pid);
                sched64_set_current(0);
            }

            if (rc == ELF64_OK && stack_ok && rsp) {
                serial64_puts("NOVARIS64: --- wineboot ---\n");
                pf_diagnose = 1;
                syscall64_set_trace(1);
                vmspace64_switch(&p->space);
                enter_user_mode64(interp.entry, rsp, 0);
                vmspace64_switch(&kspace);
                syscall64_set_trace(0);
                pf_diagnose = 0;
                serial64_puts("NOVARIS64: --- end ---\n");
            }

            /* What actually happened, reported rather than asserted.
             * This is the first run of this program on this kernel and
             * the useful output is the distance travelled, not a
             * pass/fail - an assertion here would only record which
             * step it died on. */
            serial64_puts("NOVARIS64: wineboot exit= ");
            serial64_putdec(syscall64_exit_code());
            serial64_puts(", enosys ");
            serial64_putdec(syscall64_unimplemented_count() - enosys_before);
            serial64_puts(", last ");
            serial64_putdec(syscall64_unimplemented());
            serial64_puts(", nodes ");
            serial64_putdec(ramfs64_count());
            serial64_putc('\n');

            serial64_puts("NOVARIS64: prefix  = ");
            serial64_puts(ramfs64_lookup("/root/.wine") >= 0
                          ? "/root/.wine exists" : "not created");
            serial64_puts(", system32 ");
            serial64_puts(ramfs64_lookup(
                "/root/.wine/drive_c/windows/system32") >= 0
                          ? "exists" : "absent");
            serial64_putc('\n');
        }
    }

    serial64_puts("NOVARIS64: ---- bring-up complete ----\n");

    /* --- the input watch (Milestone 70) ------------------------------
     *
     * Everything above fed the decoder by hand, which tests the decoder
     * and nothing else: those assertions all pass on a kernel whose
     * IRQ1 is masked and whose handler is never called, and the
     * "irq1 0, irq12 0" line above says exactly that.
     *
     * So the driver is installed for real here and whatever arrives is
     * printed. tools/inputtest.py sends keystrokes and mouse movement
     * through the QEMU monitor once it sees the line above, and matches
     * these lines - which is the same argument as fbtest.py taking a
     * screendump rather than asking the kernel what it drew. An
     * ordinary `make test` sends nothing, sees nothing, and prints
     * nothing here.
     */
    input64_install();

    /* Interrupts have been off since the scheduler layer put them back
     * that way, and `hlt` with IF clear is a machine that never wakes.
     * Nothing above this point needed them; everything below is
     * interrupts and nothing else. */
    __asm__ __volatile__("sti");

    serial64_puts("NOVARIS64: ---- input watch ----\n");

    for (;;) {
        input64_event_t ev;

        __asm__ __volatile__("hlt");

        while (input64_read(INPUT64_KBD, &ev, sizeof(ev)) == sizeof(ev)) {
            if (ev.type != EV64_KEY) continue;
            serial64_puts("NOVARIS64: key ");
            serial64_putdec(ev.code);
            serial64_puts(ev.value ? " down\n" : " up\n");
        }
        while (input64_read(INPUT64_MOUSE, &ev, sizeof(ev)) == sizeof(ev)) {
            if (ev.type == EV64_REL) {
                serial64_puts(ev.code == REL64_X ? "NOVARIS64: mouse x "
                                                 : "NOVARIS64: mouse y ");
                if (ev.value < 0) {
                    serial64_putc('-');
                    serial64_putdec((uint64_t)(-ev.value));
                } else {
                    serial64_putdec((uint64_t)ev.value);
                }
                serial64_putc('\n');
            } else if (ev.type == EV64_KEY) {
                serial64_puts("NOVARIS64: button ");
                serial64_putdec(ev.code);
                serial64_puts(ev.value ? " down\n" : " up\n");
            }
        }
    }
}
